-- Voucher dùng ở đơn máy bán (module pos, phiếu NT-BH-026): một dòng mỗi mã voucher của đơn, ghi cùng giao dịch với đơn.
-- Chạy bằng vai trò mod_pos_owner trong schema mod_pos: không chạm bảng Core. Mọi bảng: tenant_id, RLS, COMMENT.
-- Mã voucher do module voucher quản; bảng này để hai máy không cùng dùng một mã trong cửa sổ trước khi module voucher nhận sự kiện
-- pos.order.recorded (khoá theo mã + chỉ mục duy nhất mã đang dùng), và để huỷ đơn chờ thanh toán trả mã.
-- [2026-11-18 Võ Hoàng] NGHIEM-THU — NT-BH-026: bảng voucher dùng ở đơn máy bán (đóng góp)

CREATE TABLE voucher_uses (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint        NOT NULL,
  code           text          NOT NULL,
  order_id       text          NOT NULL,
  order_code     text          NOT NULL,
  branch_code    text          NOT NULL,
  business_date  date          NOT NULL,
  kind           text          NOT NULL CHECK (kind IN ('discount', 'payment')),
  method_code    text,
  amount         numeric(18,2) NOT NULL CHECK (amount > 0),
  face_value     numeric(18,2) NOT NULL,
  campaign_id    text          NOT NULL,
  created_at     timestamptz   NOT NULL DEFAULT now(),
  released_at    timestamptz,
  release_reason text
);
CREATE UNIQUE INDEX voucher_uses_live ON voucher_uses (tenant_id, code) WHERE released_at IS NULL;
CREATE INDEX voucher_uses_order ON voucher_uses (tenant_id, order_id);
ALTER TABLE voucher_uses ENABLE ROW LEVEL SECURITY;
ALTER TABLE voucher_uses FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON voucher_uses USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE voucher_uses IS 'Voucher dùng ở đơn máy bán (NT-BH-026): mã đang dùng (chưa trả) là duy nhất — hai máy không dùng cùng mã. Huỷ đơn chờ thanh toán → trả mã (released_at). Trả hàng không trả mã (dùng một lần).';
COMMENT ON COLUMN voucher_uses.id IS 'Số thứ tự.';
COMMENT ON COLUMN voucher_uses.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN voucher_uses.code IS 'Mã voucher (module voucher).';
COMMENT ON COLUMN voucher_uses.order_id IS 'Đơn máy bán (mod_pos.orders.order_id).';
COMMENT ON COLUMN voucher_uses.order_code IS 'Số đơn (ảnh chụp).';
COMMENT ON COLUMN voucher_uses.branch_code IS 'Cửa hàng bán.';
COMMENT ON COLUMN voucher_uses.business_date IS 'Ngày bán.';
COMMENT ON COLUMN voucher_uses.kind IS 'discount = voucher TGS (chiết khấu chia vào dòng, giảm doanh thu + thuế); payment = voucher hãng (dòng thanh toán theo hình thức kế toán khai).';
COMMENT ON COLUMN voucher_uses.method_code IS 'Hình thức thanh toán của voucher hãng (trống với voucher TGS).';
COMMENT ON COLUMN voucher_uses.amount IS 'Số tiền thực trừ (≤ mệnh giá — phần dư mất).';
COMMENT ON COLUMN voucher_uses.face_value IS 'Mệnh giá lúc dùng.';
COMMENT ON COLUMN voucher_uses.campaign_id IS 'Đợt phát (định danh ở module voucher).';
COMMENT ON COLUMN voucher_uses.created_at IS 'Lúc ghi.';
COMMENT ON COLUMN voucher_uses.released_at IS 'Lúc trả mã (huỷ đơn chờ thanh toán); trống = đang dùng.';
COMMENT ON COLUMN voucher_uses.release_reason IS 'Lý do trả mã.';
