-- Module pos đợt W2 (phiếu NT-BH-005): phiếu trả hàng / đổi hàng của máy bán + huỷ đơn. Chạy bằng vai trò mod_pos_owner trong
-- schema mod_pos; không chạm bảng Core. Chứng từ sale_return nằm ở sổ theo doc_key; bảng này giữ bản chụp để máy tra lại, in
-- lại và để tính phần còn trả được của từng dòng đơn gốc.

CREATE TABLE returns (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint        NOT NULL,
  return_id        text          NOT NULL,
  order_id         text          NOT NULL,
  branch_code      text          NOT NULL,
  code             text          NOT NULL,
  business_date    date          NOT NULL,
  refund_method    text          NOT NULL,
  refund_total     numeric(18,2) NOT NULL,
  refund_net       numeric(18,2) NOT NULL,
  refund_tax       numeric(18,2) NOT NULL,
  reason           text          NOT NULL,
  approved_by      text,
  approval_note    text,
  exchange_order_id text,
  doc_key          text          NOT NULL,
  doc_status       text          NOT NULL,
  snapshot         jsonb         NOT NULL,
  draft            jsonb         NOT NULL,
  created_by       text          NOT NULL,
  created_at       timestamptz   NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, return_id),
  UNIQUE (tenant_id, branch_code, code),
  FOREIGN KEY (tenant_id, order_id) REFERENCES orders (tenant_id, order_id)
);
CREATE INDEX returns_order ON returns (tenant_id, order_id);
CREATE INDEX returns_branch_date ON returns (tenant_id, branch_code, business_date);
ALTER TABLE returns ENABLE ROW LEVEL SECURITY;
ALTER TABLE returns FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON returns USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE returns IS 'Phiếu trả hàng máy bán POS (một dòng một phiếu). Chứng từ sale_return nối đơn gốc (originalDocKey) nằm ở sổ theo doc_key.';
COMMENT ON COLUMN returns.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN returns.return_id IS 'Id phiếu do máy sinh (UUID) — khoá chống trùng khi máy gửi lại.';
COMMENT ON COLUMN returns.order_id IS 'Đơn bán gốc (orders.order_id).';
COMMENT ON COLUMN returns.branch_code IS 'Chi nhánh nhận trả.';
COMMENT ON COLUMN returns.code IS 'Mã phiếu trả: TH + yyMM + 6 số, tăng theo chi nhánh × tháng.';
COMMENT ON COLUMN returns.business_date IS 'Ngày trả (ngày chứng từ của sale_return, quyết kỳ kế toán).';
COMMENT ON COLUMN returns.refund_method IS 'Mã hình thức trả tiền khách (tiền mặt / chuyển khoản); đổi hàng: doi_tru (đối trừ, không trả tiền).';
COMMENT ON COLUMN returns.refund_total IS 'Tiền hoàn gồm thuế (đồng).';
COMMENT ON COLUMN returns.refund_net IS 'Tiền hoàn chưa thuế (đồng).';
COMMENT ON COLUMN returns.refund_tax IS 'Thuế GTGT đầu ra giảm (đồng).';
COMMENT ON COLUMN returns.reason IS 'Lý do trả.';
COMMENT ON COLUMN returns.approved_by IS 'Người duyệt khi quá hạn trả (họp kế toán 04/11: bộ phận kinh doanh duyệt).';
COMMENT ON COLUMN returns.approval_note IS 'Lý do duyệt quá hạn.';
COMMENT ON COLUMN returns.exchange_order_id IS 'Đơn bán mới của lần đổi hàng (orders.order_id); trống = trả tiền.';
COMMENT ON COLUMN returns.doc_key IS 'docKey chứng từ sale_return: pos:<chi nhánh>:sale_return:<return_id>.';
COMMENT ON COLUMN returns.doc_status IS 'Trạng thái chứng từ lúc nộp: posted / pending / unchanged.';
COMMENT ON COLUMN returns.snapshot IS 'Phiếu trả trả cho máy (khuôn ReturnOrder của hợp đồng /pos/*).';
COMMENT ON COLUMN returns.draft IS 'Nguyên văn phiếu máy gửi (ReturnDraft).';
COMMENT ON COLUMN returns.created_by IS 'Người lập phiếu (actor id).';
COMMENT ON COLUMN returns.created_at IS 'Lúc nhận phiếu.';

CREATE TABLE return_lines (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint        NOT NULL,
  return_id          text          NOT NULL,
  order_id           text          NOT NULL,
  line_key           text          NOT NULL,
  item_id            text,
  sku                text          NOT NULL,
  unit_qty           numeric(18,4) NOT NULL,
  refund             numeric(18,2) NOT NULL,
  refund_net         numeric(18,2) NOT NULL,
  refund_tax         numeric(18,2) NOT NULL,
  UNIQUE (tenant_id, return_id, line_key),
  FOREIGN KEY (tenant_id, return_id) REFERENCES returns (tenant_id, return_id)
);
CREATE INDEX return_lines_order_line ON return_lines (tenant_id, order_id, line_key);
ALTER TABLE return_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE return_lines FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON return_lines USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE return_lines IS 'Dòng phiếu trả: phần trả của từng dòng đơn gốc — cộng các phiếu ra phần đã trả, phần còn trả được.';
COMMENT ON COLUMN return_lines.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN return_lines.return_id IS 'Phiếu trả (returns.return_id).';
COMMENT ON COLUMN return_lines.order_id IS 'Đơn bán gốc.';
COMMENT ON COLUMN return_lines.line_key IS 'Dòng của đơn gốc (lineKey / order_lines.line_key).';
COMMENT ON COLUMN return_lines.item_id IS 'Định danh mặt hàng (ảnh chụp từ dòng đơn gốc).';
COMMENT ON COLUMN return_lines.sku IS 'Mã hàng lúc bán (ảnh chụp).';
COMMENT ON COLUMN return_lines.unit_qty IS 'SL trả theo ĐVT đã bán.';
COMMENT ON COLUMN return_lines.refund IS 'Tiền hoàn gồm thuế của dòng (đồng).';
COMMENT ON COLUMN return_lines.refund_net IS 'Tiền hoàn chưa thuế của dòng (đồng).';
COMMENT ON COLUMN return_lines.refund_tax IS 'Thuế của dòng (đồng).';

ALTER TABLE orders ADD COLUMN cancelled_at timestamptz;
ALTER TABLE orders ADD COLUMN cancel_reason text;
COMMENT ON COLUMN orders.cancelled_at IS 'Lúc huỷ đơn (chỉ đơn chờ thanh toán; đơn hoàn tất dùng phiếu trả hàng).';
COMMENT ON COLUMN orders.cancel_reason IS 'Lý do huỷ.';
