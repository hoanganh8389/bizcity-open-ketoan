CREATE TABLE sale_channels (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  code            text        NOT NULL CHECK (code ~ '^[A-Z0-9_]{1,32}$'),
  name            text        NOT NULL CHECK (btrim(name) <> ''),
  kind            text        NOT NULL CHECK (kind IN ('online', 'offline')),
  sort_order      integer     NOT NULL DEFAULT 0,
  is_active       boolean     NOT NULL DEFAULT true,
  created_by      text        NOT NULL,
  created_by_name text,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_by      text        NOT NULL,
  updated_by_name text,
  updated_at      timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, code)
);
CREATE UNIQUE INDEX sale_channels_name ON sale_channels (tenant_id, lower(btrim(name)));
CREATE INDEX sale_channels_order ON sale_channels (tenant_id, sort_order, code);
ALTER TABLE sale_channels ENABLE ROW LEVEL SECURITY;
ALTER TABLE sale_channels FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON sale_channels USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
