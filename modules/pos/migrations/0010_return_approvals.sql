-- Yêu cầu trả quá hạn (module pos, phiếu NT-BH-030 Q2): quá hạn trả thì máy bán gửi yêu cầu (đủ dòng, số lượng, tình trạng, lý do),
-- người có quyền pos:return-approve (mặc định kế toán trưởng, chủ đơn vị; không phải người gửi) duyệt / từ chối; duyệt xong máy bán lập
-- phiếu trả tham chiếu yêu cầu, nội dung phải khớp. Thay cách gõ tay tên người duyệt (returns.approved_by / approval_note giữ cho phiếu cũ).
-- Chạy bằng vai trò mod_pos_owner trong schema mod_pos: không chạm bảng Core. Mọi bảng: tenant_id, RLS, COMMENT.
-- [2026-11-18 Võ Hoàng] NGHIEM-THU — NT-BH-030: bảng yêu cầu trả quá hạn + nhật ký (đóng góp)

CREATE TABLE return_approvals (
  id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id         bigint        NOT NULL,
  approval_id       text          NOT NULL,
  order_id          text          NOT NULL,
  branch_code       text          NOT NULL,
  status            text          NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'approved', 'rejected', 'used')),
  lines             jsonb         NOT NULL,
  refund_method     text          NOT NULL,
  refund_total      numeric(18,2) NOT NULL,
  reason            text          NOT NULL,
  note              text,
  deadline          date          NOT NULL,
  snapshot          jsonb         NOT NULL,
  request           jsonb         NOT NULL,
  requested_by      text          NOT NULL,
  requested_by_name text,
  requested_at      timestamptz   NOT NULL DEFAULT now(),
  decided_by        text,
  decided_by_name   text,
  decided_at        timestamptz,
  decision_note     text,
  reject_reason     text,
  return_id         text,
  used_at           timestamptz,
  UNIQUE (tenant_id, approval_id),
  FOREIGN KEY (tenant_id, order_id) REFERENCES orders (tenant_id, order_id)
);
CREATE INDEX return_approvals_order ON return_approvals (tenant_id, order_id, requested_at DESC);
CREATE INDEX return_approvals_list ON return_approvals (tenant_id, status, requested_at DESC);
ALTER TABLE return_approvals ENABLE ROW LEVEL SECURITY;
ALTER TABLE return_approvals FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON return_approvals USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE return_approvals IS 'Yêu cầu trả quá hạn của máy bán (NT-BH-030 Q2): chờ duyệt → duyệt / từ chối (quyền pos:return-approve, không phải người gửi) → máy bán lập phiếu trả đúng nội dung đã duyệt (đã dùng).';
COMMENT ON COLUMN return_approvals.id IS 'Số thứ tự.';
COMMENT ON COLUMN return_approvals.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN return_approvals.approval_id IS 'Id yêu cầu do máy sinh (UUID) — gửi lại cùng id cùng nội dung trả yêu cầu cũ.';
COMMENT ON COLUMN return_approvals.order_id IS 'Đơn bán gốc (orders.order_id).';
COMMENT ON COLUMN return_approvals.branch_code IS 'Cửa hàng nhận trả (có thể khác cửa hàng bán nếu cùng MST, NT-BH-030 Q1).';
COMMENT ON COLUMN return_approvals.status IS 'pending (chờ duyệt) / approved (đã duyệt, chưa lập phiếu) / rejected (bị từ chối) / used (đã lập phiếu trả).';
COMMENT ON COLUMN return_approvals.lines IS 'Dòng xin trả: [{ lineId, qty, condition }] — phiếu trả phải gửi đúng các dòng này.';
COMMENT ON COLUMN return_approvals.refund_method IS 'Hình thức hoàn máy dự kiến lúc gửi (tham khảo; đổi hàng: doi_tru).';
COMMENT ON COLUMN return_approvals.refund_total IS 'Tiền hoàn gồm thuế tính lúc gửi (đồng) — để người duyệt xem.';
COMMENT ON COLUMN return_approvals.reason IS 'Lý do khách trả (thu ngân ghi).';
COMMENT ON COLUMN return_approvals.note IS 'Ghi chú thêm của thu ngân.';
COMMENT ON COLUMN return_approvals.deadline IS 'Hạn trả không cần duyệt của đơn (theo hạn của cửa hàng nhận) lúc gửi.';
COMMENT ON COLUMN return_approvals.snapshot IS 'Ảnh chụp cho màn duyệt: mã đơn, cửa hàng bán, ngày bán, khách, dòng (mã, tên, SL, tình trạng, tiền hoàn).';
COMMENT ON COLUMN return_approvals.request IS 'Nguyên văn yêu cầu máy gửi.';
COMMENT ON COLUMN return_approvals.requested_by IS 'Người gửi (actor id) — không tự duyệt / từ chối.';
COMMENT ON COLUMN return_approvals.requested_by_name IS 'Tên người gửi (ảnh chụp).';
COMMENT ON COLUMN return_approvals.requested_at IS 'Lúc gửi.';
COMMENT ON COLUMN return_approvals.decided_by IS 'Người duyệt / từ chối (actor id).';
COMMENT ON COLUMN return_approvals.decided_by_name IS 'Tên người duyệt / từ chối (ảnh chụp).';
COMMENT ON COLUMN return_approvals.decided_at IS 'Lúc duyệt / từ chối.';
COMMENT ON COLUMN return_approvals.decision_note IS 'Ghi chú duyệt.';
COMMENT ON COLUMN return_approvals.reject_reason IS 'Lý do từ chối (máy bán hiện cho thu ngân).';
COMMENT ON COLUMN return_approvals.return_id IS 'Phiếu trả đã lập theo yêu cầu (returns.return_id).';
COMMENT ON COLUMN return_approvals.used_at IS 'Lúc lập phiếu trả theo yêu cầu.';

CREATE TABLE return_approval_log (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL,
  approval_id text        NOT NULL,
  action      text        NOT NULL CHECK (action IN ('submit', 'approve', 'reject', 'use')),
  actor       text        NOT NULL,
  actor_name  text,
  note        text,
  at          timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX return_approval_log_key ON return_approval_log (tenant_id, approval_id, at);
ALTER TABLE return_approval_log ENABLE ROW LEVEL SECURITY;
ALTER TABLE return_approval_log FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON return_approval_log USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE return_approval_log IS 'Nhật ký yêu cầu trả quá hạn: gửi, duyệt, từ chối, lập phiếu — người, lúc, lý do. Chỉ thêm.';
COMMENT ON COLUMN return_approval_log.id IS 'Số thứ tự.';
COMMENT ON COLUMN return_approval_log.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN return_approval_log.approval_id IS 'Yêu cầu (return_approvals.approval_id).';
COMMENT ON COLUMN return_approval_log.action IS 'submit (gửi) / approve (duyệt) / reject (từ chối) / use (lập phiếu trả).';
COMMENT ON COLUMN return_approval_log.actor IS 'Người làm (actor id).';
COMMENT ON COLUMN return_approval_log.actor_name IS 'Tên người làm (ảnh chụp).';
COMMENT ON COLUMN return_approval_log.note IS 'Lý do / ghi chú (từ chối: lý do; lập phiếu: mã phiếu trả).';
COMMENT ON COLUMN return_approval_log.at IS 'Lúc làm.';
