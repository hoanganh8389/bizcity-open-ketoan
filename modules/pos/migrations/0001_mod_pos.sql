-- Module pos (kế hoạch module POS đợt W1): đơn bán của máy bán POS + bộ đếm số phiếu. Chạy bằng vai trò mod_pos_owner trong schema mod_pos
-- (`npm run module -w @ketoan/api -- migrate pos`): không chạm bảng Core. Mọi bảng: tenant_id, RLS, COMMENT.

CREATE TABLE orders (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint        NOT NULL,
  order_id       text          NOT NULL,
  branch_code    text          NOT NULL,
  code           text          NOT NULL,
  business_date  date          NOT NULL,
  status         text          NOT NULL CHECK (status IN ('completed', 'awaiting_payment', 'cancelled')),
  customer_code  text,
  subtotal       numeric(18,2) NOT NULL,
  tax_total      numeric(18,2) NOT NULL,
  total          numeric(18,2) NOT NULL,
  doc_key        text          NOT NULL,
  doc_status     text          NOT NULL,
  snapshot       jsonb         NOT NULL,
  draft          jsonb         NOT NULL,
  created_by     text          NOT NULL,
  created_at     timestamptz   NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, order_id),
  UNIQUE (tenant_id, branch_code, code)
);
CREATE INDEX orders_branch_date ON orders (tenant_id, branch_code, business_date);
ALTER TABLE orders ENABLE ROW LEVEL SECURITY;
ALTER TABLE orders FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON orders USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE orders IS 'Đơn bán máy bán POS gửi lên (một dòng một đơn). Chứng từ sale tương ứng nằm ở sổ theo doc_key; bảng này giữ bản chụp để máy tra lại, in lại.';
COMMENT ON COLUMN orders.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN orders.order_id IS 'Id đơn do máy sinh (UUID, cố định theo tab hoá đơn) — khoá chống trùng khi máy gửi lại.';
COMMENT ON COLUMN orders.branch_code IS 'Mã chi nhánh bán (bizcity_read.branches.code).';
COMMENT ON COLUMN orders.code IS 'Mã phiếu bán: HD + yyMM + 6 số, tăng theo chi nhánh × tháng của ngày bán.';
COMMENT ON COLUMN orders.business_date IS 'Ngày bán (ngày chứng từ của chứng từ sale, quyết kỳ kế toán).';
COMMENT ON COLUMN orders.status IS 'completed = đã thu đủ; awaiting_payment = chờ QR (đợt sau); cancelled = đã huỷ (đợt sau).';
COMMENT ON COLUMN orders.customer_code IS 'Mã khách trên chứng từ (SĐT hoặc mã khách); trống = khách lẻ.';
COMMENT ON COLUMN orders.subtotal IS 'Tổng tiền hàng chưa thuế sau giảm giá (đồng).';
COMMENT ON COLUMN orders.tax_total IS 'Tổng tiền thuế GTGT (đồng).';
COMMENT ON COLUMN orders.total IS 'Khách phải trả, gồm thuế (đồng).';
COMMENT ON COLUMN orders.doc_key IS 'docKey chứng từ sale đã nộp: pos:<chi nhánh>:sale:<order_id>.';
COMMENT ON COLUMN orders.doc_status IS 'Trạng thái chứng từ lúc nộp: posted (đã ghi sổ) / pending (chờ duyệt ở ACC14) / unchanged.';
COMMENT ON COLUMN orders.snapshot IS 'Đơn trả cho máy (khuôn Order của hợp đồng /pos/*), dùng khi máy tra lại / gửi lặp.';
COMMENT ON COLUMN orders.draft IS 'Nguyên văn đơn máy gửi (OrderDraft) — để đối chiếu khi có chênh.';
COMMENT ON COLUMN orders.created_by IS 'Người gửi đơn (actor id: user:N hoặc apikey:N).';
COMMENT ON COLUMN orders.created_at IS 'Lúc nhận đơn.';

CREATE TABLE code_counters (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL,
  branch_code text        NOT NULL,
  kind        text        NOT NULL CHECK (kind IN ('sale', 'return')),
  period      text        NOT NULL,
  last_no     integer     NOT NULL DEFAULT 0 CHECK (last_no >= 0),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, branch_code, kind, period)
);
ALTER TABLE code_counters ENABLE ROW LEVEL SECURITY;
ALTER TABLE code_counters FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON code_counters USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE code_counters IS 'Bộ đếm số phiếu của máy bán theo chi nhánh × loại × tháng. Cấp trước cho máy được (nhảy số chấp nhận, Q20).';
COMMENT ON COLUMN code_counters.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN code_counters.branch_code IS 'Mã chi nhánh.';
COMMENT ON COLUMN code_counters.kind IS 'sale = phiếu bán (HD…), return = phiếu hoàn (TH…).';
COMMENT ON COLUMN code_counters.period IS 'Tháng của số phiếu, dạng yyMM.';
COMMENT ON COLUMN code_counters.last_no IS 'Số cuối đã cấp trong tháng.';
COMMENT ON COLUMN code_counters.updated_at IS 'Lúc cấp số gần nhất.';
