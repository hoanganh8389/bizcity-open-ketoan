CREATE TABLE code_reservations (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint      NOT NULL,
  branch_code      text        NOT NULL,
  kind             text        NOT NULL CHECK (kind IN ('sale', 'return')),
  codes            text[]      NOT NULL,
  business_date    date        NOT NULL,
  device_id        text,
  reserved_by      text        NOT NULL,
  reserved_by_name text,
  reserved_at      timestamptz NOT NULL DEFAULT now(),
  expires_at       timestamptz NOT NULL
);
CREATE INDEX code_reservations_branch_date ON code_reservations (tenant_id, branch_code, business_date);
ALTER TABLE code_reservations ENABLE ROW LEVEL SECURITY;
ALTER TABLE code_reservations FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON code_reservations USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE code_reservations IS 'Dải số phiếu máy bán xin trước (NT-BH-027): số đã cấp mà không đơn / phiếu nào dùng là số thiếu (chấp nhận hở số khi mất mạng, Q2) — báo cáo GET /reports/missing-codes.';
COMMENT ON COLUMN code_reservations.id IS 'Số thứ tự.';
COMMENT ON COLUMN code_reservations.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN code_reservations.branch_code IS 'Cửa hàng (mã chi nhánh = mã shop).';
COMMENT ON COLUMN code_reservations.kind IS 'sale = phiếu bán; return = phiếu hoàn.';
COMMENT ON COLUMN code_reservations.codes IS 'Các mã đã cấp trong lần xin (liên tiếp, theo dạng của cửa hàng lúc xin: HD… hoặc {shop}BT…).';
COMMENT ON COLUMN code_reservations.business_date IS 'Ngày bán máy xin dải (ngày của báo cáo số thiếu).';
COMMENT ON COLUMN code_reservations.device_id IS 'Mã máy bán gửi kèm khi xin (trống = máy không gửi; báo cáo nêu người xin).';
COMMENT ON COLUMN code_reservations.reserved_by IS 'Người xin (actor id).';
COMMENT ON COLUMN code_reservations.reserved_by_name IS 'Tên người xin lúc xin (ảnh chụp).';
COMMENT ON COLUMN code_reservations.reserved_at IS 'Lúc cấp dải.';
COMMENT ON COLUMN code_reservations.expires_at IS 'Hạn dùng dải báo cho máy (quá hạn máy xin dải mới; số chưa dùng ghi lý do hết hạn).';
COMMENT ON COLUMN code_counters.period IS 'Tháng của số phiếu dạng HD / TH (yyMM); SHOP = bộ đếm liên tục của dạng shop (NT-BH-027).';
