CREATE TABLE promo_drafts (
  draft_id          uuid        NOT NULL PRIMARY KEY,
  tenant_id         bigint      NOT NULL,
  policy_key        text        NOT NULL,
  rule_contract     text        NOT NULL,
  params            jsonb       NOT NULL,
  branch_codes      jsonb       NOT NULL DEFAULT '[]'::jsonb,
  effective_from    date        NOT NULL,
  reason            text,
  quota             jsonb,
  status            text        NOT NULL DEFAULT 'draft' CHECK (status IN ('draft', 'pending', 'approved', 'published', 'rejected')),
  source            text        NOT NULL DEFAULT 'screen' CHECK (source IN ('screen', 'migrate')),
  source_ref        text,
  created_by        text        NOT NULL,
  created_by_name   text,
  created_at        timestamptz NOT NULL DEFAULT now(),
  updated_by        text        NOT NULL,
  updated_at        timestamptz NOT NULL DEFAULT now(),
  approved_by       text,
  approved_by_name  text,
  approved_at       timestamptz,
  reject_reason     text,
  published_version integer,
  published_at      timestamptz
);
CREATE UNIQUE INDEX promo_drafts_open_key ON promo_drafts (tenant_id, policy_key) WHERE status IN ('draft', 'pending', 'approved', 'rejected');
CREATE UNIQUE INDEX promo_drafts_source_ref ON promo_drafts (tenant_id, source_ref) WHERE source_ref IS NOT NULL;
CREATE INDEX promo_drafts_list ON promo_drafts (tenant_id, status, updated_at DESC);
ALTER TABLE promo_drafts ENABLE ROW LEVEL SECURITY;
ALTER TABLE promo_drafts FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON promo_drafts USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE promo_drafts IS 'Bản nháp chương trình khuyến mại (BH18): lập / sửa → chờ duyệt → duyệt (người khác người lập, quyền pos:promo-approve) → màn phát hành vào sổ chính sách của Core → ghi bản đã phát hành. Từ chối → sửa lại được.';
