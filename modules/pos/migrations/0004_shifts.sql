-- Module pos đợt W3 (phiếu NT-BH-007): ca bán của chi nhánh — mở ca (tiền đầu ca), chốt ca (đếm két, chênh lệch, biên bản).
-- Chạy bằng vai trò mod_pos_owner trong schema mod_pos; không chạm bảng Core. Chốt ca không lập chứng từ (NT-BH-007 Q1: chênh lệch
-- kế toán xử lý tay cho tới khi chốt khác). Số liệu ca tính từ đơn / phiếu trả của chi nhánh trong khoảng mở → chốt.

CREATE TABLE shifts (
  id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint        NOT NULL,
  shift_id         text          NOT NULL,
  branch_code      text          NOT NULL,
  status           text          NOT NULL CHECK (status IN ('open', 'closed')),
  opened_at        timestamptz   NOT NULL DEFAULT now(),
  opened_by        text          NOT NULL,
  opened_by_name   text          NOT NULL DEFAULT '',
  opening_cash     numeric(18,2) NOT NULL CHECK (opening_cash >= 0),
  closed_at        timestamptz,
  closed_by        text,
  counted_cash     numeric(18,2),
  expected_cash    numeric(18,2),
  difference       numeric(18,2),
  forced           boolean       NOT NULL DEFAULT false,
  note             text,
  report           jsonb,
  UNIQUE (tenant_id, shift_id),
  CHECK ((status = 'closed') = (closed_at IS NOT NULL))
);
-- Một chi nhánh chỉ một ca đang mở (NT-BH-007 §2; Q3 mặc định một ca chung / chi nhánh).
CREATE UNIQUE INDEX shifts_one_open ON shifts (tenant_id, branch_code) WHERE status = 'open';
CREATE INDEX shifts_branch_opened ON shifts (tenant_id, branch_code, opened_at DESC);
ALTER TABLE shifts ENABLE ROW LEVEL SECURITY;
ALTER TABLE shifts FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON shifts USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE shifts IS 'Ca bán máy POS theo chi nhánh: mở (tiền đầu ca) → chốt (đếm két, chênh lệch, biên bản). Không ghi sổ.';
COMMENT ON COLUMN shifts.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN shifts.shift_id IS 'Id ca (máy bán dùng làm shiftId của đơn).';
COMMENT ON COLUMN shifts.id IS 'Khoá nội bộ.';
COMMENT ON COLUMN shifts.branch_code IS 'Chi nhánh của ca (một chi nhánh chỉ một ca mở).';
COMMENT ON COLUMN shifts.status IS 'open = đang mở; closed = đã chốt.';
COMMENT ON COLUMN shifts.opened_at IS 'Giờ mở ca.';
COMMENT ON COLUMN shifts.opened_by IS 'Người mở ca (id người dùng Core).';
COMMENT ON COLUMN shifts.opened_by_name IS 'Tên người mở ca lúc mở (ảnh chụp).';
COMMENT ON COLUMN shifts.closed_at IS 'Giờ chốt ca; NULL khi đang mở.';
COMMENT ON COLUMN shifts.closed_by IS 'Người chốt ca (id người dùng Core).';
COMMENT ON COLUMN shifts.counted_cash IS 'Lúc chốt: tiền mặt đếm được trong két.';
COMMENT ON COLUMN shifts.note IS 'Ghi chú / lý do khi chốt (bắt buộc khi chốt bất chấp).';
COMMENT ON COLUMN shifts.opening_cash IS 'Tiền mặt đầu ca trong két.';
COMMENT ON COLUMN shifts.expected_cash IS 'Lúc chốt: tiền đầu ca + tiền mặt thu từ đơn − tiền mặt chi hoàn.';
COMMENT ON COLUMN shifts.difference IS 'Lúc chốt: tiền đếm được − tiền phải có (âm = thiếu).';
COMMENT ON COLUMN shifts.forced IS 'Chốt khi còn việc dở (đơn chờ trả tiền…), có ghi lý do ở note.';
COMMENT ON COLUMN shifts.report IS 'Biên bản chốt ca (bản chụp ShiftReport) — gửi lại cùng khoá trả đúng biên bản này.';
