-- Module pos: dòng đơn lưu định danh mặt hàng (item_id, ADR-0017 / ADR-0028 D028-4 / STD-DATA-6). Mã hàng, tên, ĐVT chỉ là
-- ảnh chụp lúc bán để in lại. Chạy bằng vai trò mod_pos_owner trong schema mod_pos; không chạm bảng Core.
-- Chi nhánh và khách vẫn lưu theo mã ở orders: khung nhìn bizcity_read.branches / partners chưa lộ định danh (ghi nợ, đề xuất Core).

CREATE TABLE order_lines (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint        NOT NULL,
  order_id           text          NOT NULL,
  line_key           text          NOT NULL,
  item_id            text,
  sku                text          NOT NULL,
  item_name          text          NOT NULL DEFAULT '',
  unit_name          text          NOT NULL DEFAULT '',
  unit_qty           numeric(18,4) NOT NULL,
  unit_ratio         numeric(18,4) NOT NULL DEFAULT 1,
  amount             numeric(18,2) NOT NULL,
  amount_before_tax  numeric(18,2) NOT NULL,
  tax_amount         numeric(18,2) NOT NULL,
  discount           numeric(18,2) NOT NULL DEFAULT 0,
  tax_code           text          NOT NULL,
  send_tax           boolean       NOT NULL DEFAULT true,
  UNIQUE (tenant_id, order_id, line_key),
  FOREIGN KEY (tenant_id, order_id) REFERENCES orders (tenant_id, order_id)
);
CREATE INDEX order_lines_item ON order_lines (tenant_id, item_id);
ALTER TABLE order_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE order_lines FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON order_lines USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE order_lines IS 'Dòng đơn bán máy POS: định danh mặt hàng + tiền từng dòng như chứng từ sale đã nộp.';
COMMENT ON COLUMN order_lines.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN order_lines.order_id IS 'Id đơn (orders.order_id).';
COMMENT ON COLUMN order_lines.line_key IS 'Khoá dòng do máy sinh (lineKey của chứng từ sale).';
COMMENT ON COLUMN order_lines.item_id IS 'Định danh bất biến của mặt hàng (bizcity_read.products.item_id); trống khi danh mục chưa có.';
COMMENT ON COLUMN order_lines.sku IS 'Mã hàng lúc bán (ảnh chụp, không dùng làm khoá).';
COMMENT ON COLUMN order_lines.item_name IS 'Tên hàng lúc bán (ảnh chụp để in lại).';
COMMENT ON COLUMN order_lines.unit_name IS 'ĐVT bán.';
COMMENT ON COLUMN order_lines.unit_qty IS 'Số lượng theo ĐVT bán.';
COMMENT ON COLUMN order_lines.unit_ratio IS 'Tỉ lệ ĐVT bán / đơn vị nhỏ nhất.';
COMMENT ON COLUMN order_lines.amount IS 'Thành tiền gồm thuế sau giảm (đồng).';
COMMENT ON COLUMN order_lines.amount_before_tax IS 'Thành tiền chưa thuế sau giảm (đồng) — amountBeforeTax của chứng từ.';
COMMENT ON COLUMN order_lines.tax_amount IS 'Tiền thuế GTGT (đồng).';
COMMENT ON COLUMN order_lines.discount IS 'Tiền giảm tay chưa thuế (đồng).';
COMMENT ON COLUMN order_lines.tax_code IS 'Mã thuế đầu ra lúc bán.';
COMMENT ON COLUMN order_lines.send_tax IS 'Gửi lên thuế lúc bán (false = không lên hoá đơn thuế).';
COMMENT ON COLUMN orders.customer_code IS 'Mã khách trên chứng từ (SĐT hoặc mã khách); trống = khách lẻ. Dữ liệu cá nhân khi là SĐT (STD-DATA-10).';
