-- Module mẫu (module mau-module): bảng bản ghi theo đơn vị. Chạy bằng vai trò mod_mau_module_owner trong schema mod_mau_module
-- (`npm run module -w @ketoan/api -- migrate mau-module`): không tạo / sửa được bảng của Core. Mọi bảng: tenant_id, RLS, COMMENT.
CREATE TABLE records (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL,
  title       text        NOT NULL,
  note        text,
  created_by  text        NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now()
);
ALTER TABLE records ENABLE ROW LEVEL SECURITY;
ALTER TABLE records FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON records USING (public.bizcity_tenant_visible(tenant_id)) WITH CHECK (public.bizcity_tenant_visible(tenant_id));
COMMENT ON TABLE records IS 'Module mẫu: bản ghi của đơn vị.';
COMMENT ON COLUMN records.tenant_id IS 'Đơn vị (RLS).';
COMMENT ON COLUMN records.title IS 'Tiêu đề.';
COMMENT ON COLUMN records.note IS 'Ghi chú (tuỳ chọn).';
COMMENT ON COLUMN records.created_by IS 'Người lập (actor id).';
COMMENT ON COLUMN records.created_at IS 'Lúc lập.';
