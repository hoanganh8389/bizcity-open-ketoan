CREATE TABLE IF NOT EXISTS conformance_runs (
  id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint      NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  as_of            date        NOT NULL,
  layers           text[]      NOT NULL,
  profile_version  integer,
  kit_version      text,
  kit_hash         text        NOT NULL,
  result           text        NOT NULL CHECK (result IN ('PASS', 'FAIL', 'REVIEW_REQUIRED')),
  counts           jsonb       NOT NULL,
  report           jsonb       NOT NULL,
  actor            text        NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS conformance_runs_tenant_idx ON conformance_runs (tenant_id, id DESC);

CREATE OR REPLACE FUNCTION conformance_runs_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' AND pg_trigger_depth() > 1 THEN RETURN OLD; END IF;
  RAISE EXCEPTION 'Lượt Kiểm chuẩn đã lưu không sửa / xoá được (chỉ thêm)' USING ERRCODE = 'P0001';
END $$;
DROP TRIGGER IF EXISTS conformance_runs_guard ON conformance_runs;
CREATE TRIGGER conformance_runs_guard BEFORE UPDATE OR DELETE ON conformance_runs FOR EACH ROW EXECUTE FUNCTION conformance_runs_guard();

ALTER TABLE conformance_runs ENABLE ROW LEVEL SECURITY;
ALTER TABLE conformance_runs FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON conformance_runs;
CREATE POLICY tenant_isolation ON conformance_runs USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));

COMMENT ON TABLE conformance_runs IS 'Lượt Kiểm chuẩn của đơn vị (Conformance Engine, ADR-0012): ảnh chụp báo cáo, chỉ thêm. Phân tích để người dùng quyết định, không chặn ghi sổ.';
COMMENT ON COLUMN conformance_runs.id IS 'Số lượt.';
COMMENT ON COLUMN conformance_runs.tenant_id IS 'Đơn vị.';
COMMENT ON COLUMN conformance_runs.as_of IS 'Ngày đánh giá: chọn hồ sơ kế toán và rulepack có hiệu lực tại ngày này.';
COMMENT ON COLUMN conformance_runs.layers IS 'Lớp đã đánh giá trong lượt: module, configuration, enterprise (ADR-0012).';
COMMENT ON COLUMN conformance_runs.profile_version IS 'Phiên bản hồ sơ kế toán đã dùng (accounting_profiles.version); NULL = đơn vị chưa khai.';
COMMENT ON COLUMN conformance_runs.kit_version IS 'Phiên bản gói @bizcity/vn-rulepacks lúc chạy.';
COMMENT ON COLUMN conformance_runs.kit_hash IS 'SHA-256 nội dung kho rulepack + nguồn pháp lý lúc chạy (biết chính xác bộ quy định nào đã dùng).';
COMMENT ON COLUMN conformance_runs.result IS 'Kết quả tổng: PASS · FAIL · REVIEW_REQUIRED (R-VNC-8; REVIEW_REQUIRED và NOT_TESTED không bao giờ là PASS).';
COMMENT ON COLUMN conformance_runs.counts IS 'Số ca theo trạng thái: PASS, FAIL, ERROR, NOT_APPLICABLE, NOT_TESTED, REVIEW_REQUIRED.';
COMMENT ON COLUMN conformance_runs.report IS 'Báo cáo bizcity_vn_conformance_report@1 nguyên văn (không số tiền, không tên khách — chỉ mã kiểm, mã ca, lý do).';
COMMENT ON COLUMN conformance_runs.actor IS 'Người chạy (hoặc lịch chạy).';
COMMENT ON COLUMN conformance_runs.created_at IS 'Lúc chạy.';
