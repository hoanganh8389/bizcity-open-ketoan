-- ── Vai trò của đơn vị ─────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE tenant_roles (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL REFERENCES tenants(id),
  code        text        NOT NULL CHECK (code ~ '^[a-z][a-z0-9_-]{1,39}$'
                                          AND code NOT IN ('owner', 'chief_accountant', 'accountant', 'viewer', 'developer', 'auditor')),
  label       text        NOT NULL CHECK (length(btrim(label)) BETWEEN 1 AND 120),
  kind        text        NOT NULL CHECK (kind IN ('job', 'privilege', 'restriction')),
  base_role   text        CHECK (base_role IN ('chief_accountant', 'accountant', 'viewer', 'developer', 'auditor')),
  is_active   boolean     NOT NULL DEFAULT true,
  version     integer     NOT NULL DEFAULT 1 CHECK (version >= 1),
  created_by  text        NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  text,
  updated_at  timestamptz,
  CONSTRAINT tenant_roles_code_uq UNIQUE (tenant_id, code),
  CONSTRAINT tenant_roles_tenant_id_uq UNIQUE (tenant_id, id),
  CONSTRAINT tenant_roles_restriction_chk CHECK (kind <> 'restriction' OR base_role IS NULL)
);

COMMENT ON TABLE tenant_roles IS 'Vai trò của đơn vị (ADR-0027 Phụ lục A, D-AUTH-11): vai trò nền + luật Cho / Cấm ở tenant_role_rules. Không xoá — vô hiệu bằng is_active; mã, loại, vai trò nền bất biến.';
COMMENT ON COLUMN tenant_roles.id IS 'Định danh vai trò; lần gán trỏ vào đây (user_role_assignments.tenant_role_id), không trỏ mã.';
COMMENT ON COLUMN tenant_roles.tenant_id IS 'Đơn vị.';
COMMENT ON COLUMN tenant_roles.code IS 'Mã vai trò, duy nhất theo đơn vị, không trùng 6 mã vai trò hệ thống. Bất biến.';
COMMENT ON COLUMN tenant_roles.label IS 'Tên hiển thị (vd "Thủ kho"). Sửa được, kèm tăng version.';
COMMENT ON COLUMN tenant_roles.kind IS 'job: vai trò công việc; privilege: đặc quyền thêm; restriction: chỉ để Cấm (không có vai trò nền). Bất biến.';
COMMENT ON COLUMN tenant_roles.base_role IS 'Vai trò hệ thống làm nền (kế thừa một cấp, D-AUTH-14); không bao giờ là owner. NULL = không nền. Bất biến — đổi nền = vai trò mới.';
COMMENT ON COLUMN tenant_roles.is_active IS 'false = vô hiệu: lần gán còn đó nhưng không cấp gì.';
COMMENT ON COLUMN tenant_roles.version IS 'Tăng đúng 1 ở mỗi lần sửa tên / bật tắt (trigger kiểm).';
COMMENT ON COLUMN tenant_roles.created_by IS 'Người tạo (user:<id>).';
COMMENT ON COLUMN tenant_roles.created_at IS 'Lúc tạo.';
COMMENT ON COLUMN tenant_roles.updated_by IS 'Người sửa gần nhất (bắt buộc khi sửa).';
COMMENT ON COLUMN tenant_roles.updated_at IS 'Lúc sửa gần nhất (bắt buộc khi sửa).';

CREATE OR REPLACE FUNCTION bizcity_tenant_roles_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Vai trò của đơn vị không xoá (ADR-0027 Phụ lục A): vô hiệu bằng is_active = false.' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF (NEW.tenant_id, NEW.code, NEW.kind, NEW.base_role, NEW.created_by, NEW.created_at)
     IS DISTINCT FROM (OLD.tenant_id, OLD.code, OLD.kind, OLD.base_role, OLD.created_by, OLD.created_at) THEN
    RAISE EXCEPTION 'Vai trò % : mã, loại, vai trò nền bất biến (ADR-0027 Phụ lục A) — đổi nền / loại = tạo vai trò mới.', OLD.id USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF NEW.version <> OLD.version + 1 OR NEW.updated_by IS NULL OR NEW.updated_at IS NULL THEN
    RAISE EXCEPTION 'Sửa vai trò % phải tăng version đúng 1 và ghi updated_by / updated_at.', OLD.id USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;
COMMENT ON FUNCTION bizcity_tenant_roles_guard() IS 'Bất biến tenant_roles (ADR-0027 Phụ lục A): không xoá; mã / loại / nền không đổi; mỗi lần sửa tăng version 1.';
CREATE TRIGGER tenant_roles_guard BEFORE UPDATE OR DELETE ON tenant_roles FOR EACH ROW EXECUTE FUNCTION bizcity_tenant_roles_guard();

-- ── Luật của vai trò ───────────────────────────────────────────────────────────────────────────────────────────────────
CREATE TABLE tenant_role_rules (
  id              bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL,
  tenant_role_id  bigint      NOT NULL,
  permission      text        NOT NULL CHECK (permission ~ '^[a-z*][a-z0-9*-]*:[a-z*][a-z0-9*-]*$'),
  effect          text        NOT NULL CHECK (effect IN ('allow', 'deny')),
  conditions      jsonb       NOT NULL DEFAULT '{}'::jsonb CHECK (conditions = '{}'::jsonb),
  note            text,
  created_by      text        NOT NULL,
  created_at      timestamptz NOT NULL DEFAULT now(),
  removed_by      text,
  removed_at      timestamptz,
  remove_reason   text,
  CONSTRAINT tenant_role_rules_role_fk FOREIGN KEY (tenant_id, tenant_role_id) REFERENCES tenant_roles (tenant_id, id),
  CONSTRAINT tenant_role_rules_allow_exact_chk CHECK (effect <> 'allow' OR position('*' IN permission) = 0),
  CONSTRAINT tenant_role_rules_remove_chk CHECK ((removed_at IS NULL) = (removed_by IS NULL) AND (removed_at IS NULL OR length(btrim(coalesce(remove_reason, ''))) >= 3))
);

COMMENT ON TABLE tenant_role_rules IS 'Luật Cho / Cấm của vai trò của đơn vị (ADR-0027 Phụ lục A, D-AUTH-12). Chỉ thêm; gỡ luật bằng removed_* một lần. Nới (relax) và điều kiện: bước 4.';
COMMENT ON COLUMN tenant_role_rules.id IS 'Định danh luật.';
COMMENT ON COLUMN tenant_role_rules.tenant_id IS 'Đơn vị; khoá ngoại ghép với tenant_role_id nên luật không trỏ vai trò của đơn vị khác.';
COMMENT ON COLUMN tenant_role_rules.tenant_role_id IS 'Vai trò chứa luật.';
COMMENT ON COLUMN tenant_role_rules.permission IS 'Quyền <module>:<việc>. Cho: đích danh; Cấm: được dùng *. Quyền phải có trong sổ quyền của code (kiểm ở API).';
COMMENT ON COLUMN tenant_role_rules.effect IS 'allow (Cho) | deny (Cấm, thắng mọi Cho trong cùng phạm vi).';
COMMENT ON COLUMN tenant_role_rules.conditions IS 'Điều kiện của luật (bizcity_authorization@1 §5); bước 1 luôn {}.';
COMMENT ON COLUMN tenant_role_rules.note IS 'Ghi chú của người lập.';
COMMENT ON COLUMN tenant_role_rules.created_by IS 'Người thêm luật (user:<id>).';
COMMENT ON COLUMN tenant_role_rules.created_at IS 'Lúc thêm.';
COMMENT ON COLUMN tenant_role_rules.removed_by IS 'Người gỡ luật; NULL = đang áp dụng.';
COMMENT ON COLUMN tenant_role_rules.removed_at IS 'Lúc gỡ; đặt một lần.';
COMMENT ON COLUMN tenant_role_rules.remove_reason IS 'Lý do gỡ (bắt buộc khi gỡ).';

CREATE UNIQUE INDEX tenant_role_rules_open_uq ON tenant_role_rules (tenant_role_id, permission, effect) WHERE removed_at IS NULL;

CREATE OR REPLACE FUNCTION bizcity_tenant_role_rules_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Luật vai trò chỉ thêm (ADR-0027 Phụ lục A): không xoá, gỡ bằng removed_at.' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF OLD.removed_at IS NOT NULL THEN
    RAISE EXCEPTION 'Luật vai trò % đã gỡ, không sửa lại.', OLD.id USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF (NEW.tenant_id, NEW.tenant_role_id, NEW.permission, NEW.effect, NEW.conditions, NEW.note, NEW.created_by, NEW.created_at)
     IS DISTINCT FROM (OLD.tenant_id, OLD.tenant_role_id, OLD.permission, OLD.effect, OLD.conditions, OLD.note, OLD.created_by, OLD.created_at) THEN
    RAISE EXCEPTION 'Luật vai trò chỉ thêm (ADR-0027 Phụ lục A): đổi luật = gỡ luật cũ + thêm luật mới.' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;
COMMENT ON FUNCTION bizcity_tenant_role_rules_guard() IS 'Bất biến tenant_role_rules (ADR-0027 Phụ lục A): không xoá; UPDATE duy nhất là đặt removed_* một lần.';
CREATE TRIGGER tenant_role_rules_guard BEFORE UPDATE OR DELETE ON tenant_role_rules FOR EACH ROW EXECUTE FUNCTION bizcity_tenant_role_rules_guard();

