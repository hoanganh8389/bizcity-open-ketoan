-- [2026-11-15 Nguyễn Văn Thủy] Quy tắc hạch toán gọn: Mục đích xuất thay lý do; bỏ bảng quy tắc định khoản có điều kiện và TK ngầm định theo loại chứng từ (đóng góp)
--
-- Tài khoản của mọi bút toán tự động lấy từ đúng một trong năm nguồn (docs/nghiep-vu/24-quy-tac-hach-toan.md):
--   tài khoản của quy tắc (posting_defaults), hình thức thanh toán, loại kho, loại thuế, MỤC ĐÍCH XUẤT (bảng mới dưới đây).
--
-- stock_purposes: phiếu xuất kho không bán / điều chỉnh kho ghi mục đích (hủy hàng hỏng, dùng cho bộ phận bán hàng, tặng khách
--   dùng thử…) → tài khoản đối ứng. direction: dùng cho phiếu giảm kho (decrease), tăng kho (increase) hay cả hai (both).
--   Không xoá dòng đã dùng: ngừng dùng bằng is_active.
-- Bỏ:
--   posting_rules, posting_businesses (0096): bảng quy tắc định khoản có điều kiện đè tài khoản.
--   account_default_types (0126): 133 loại chứng từ × cột tài khoản — thay bằng màn Quy tắc hạch toán (khung cố định trong code).
--   Khoá cấu hình bizcity.posting.use_reasons: bộ định khoản không còn đọc (lý do không đổi tài khoản); dòng cũ để nguyên.

CREATE TABLE stock_purposes (
  id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id    bigint NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  code         text NOT NULL CHECK (code ~ '^[A-Z0-9][A-Z0-9_-]{0,31}$'),
  name         text NOT NULL CHECK (btrim(name) <> ''),
  direction    text NOT NULL DEFAULT 'decrease' CHECK (direction IN ('increase', 'decrease', 'both')),
  account_code text NOT NULL CHECK (account_code ~ '^[0-9]{3,20}$'),
  is_active    boolean NOT NULL DEFAULT true,
  sort_order   integer NOT NULL DEFAULT 0,
  updated_by   text NOT NULL DEFAULT '',
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, code)
);
COMMENT ON TABLE stock_purposes IS 'Mục đích xuất (0140): phiếu xuất kho không bán / điều chỉnh kho → TK đối ứng (hủy, mất, dùng cho bộ phận, tặng, đào tạo…).';
COMMENT ON COLUMN stock_purposes.direction IS 'Dùng cho phiếu giảm kho (decrease), tăng kho (increase) hay cả hai (both).';
COMMENT ON COLUMN stock_purposes.account_code IS 'Tài khoản đối ứng (tài khoản chi tiết, trong phạm vi cho phép của màn Quy tắc hạch toán).';

ALTER TABLE stock_purposes ENABLE ROW LEVEL SECURITY;
ALTER TABLE stock_purposes FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON stock_purposes USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ketoan_app') THEN
    GRANT SELECT, INSERT, UPDATE ON stock_purposes TO ketoan_app;
    GRANT USAGE ON SEQUENCE stock_purposes_id_seq TO ketoan_app;
  END IF;
END $$;

DROP TABLE IF EXISTS posting_rules;
DROP TABLE IF EXISTS posting_businesses;
DROP TABLE IF EXISTS account_default_types;
