CREATE TABLE IF NOT EXISTS notifications (
  id                   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id            bigint      NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  source               text        NOT NULL,
  recipient_user_id    bigint      REFERENCES users(id) ON DELETE CASCADE,
  audience_permission  text,
  title                text        NOT NULL CHECK (length(btrim(title)) BETWEEN 1 AND 200),
  body                 text        CHECK (body IS NULL OR length(body) <= 2000),
  link                 text        CHECK (link IS NULL OR link ~ '^/'),
  dedupe_key           text,
  created_at           timestamptz NOT NULL DEFAULT now(),
  CHECK ((recipient_user_id IS NULL) <> (audience_permission IS NULL))
);
CREATE UNIQUE INDEX IF NOT EXISTS notifications_dedupe_uq ON notifications (tenant_id, source, dedupe_key) WHERE dedupe_key IS NOT NULL;
CREATE INDEX IF NOT EXISTS notifications_tenant_idx ON notifications (tenant_id, id DESC);

CREATE TABLE IF NOT EXISTS notification_reads (
  notification_id  bigint      NOT NULL REFERENCES notifications(id) ON DELETE CASCADE,
  user_id          bigint      NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  tenant_id        bigint      NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  read_at          timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (notification_id, user_id)
);

ALTER TABLE notifications ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON notifications;
CREATE POLICY tenant_isolation ON notifications USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));
ALTER TABLE notification_reads ENABLE ROW LEVEL SECURITY;
