--
-- Name: posted_event_payloads; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.posted_event_payloads AS
 SELECT id,
    tenant_id,
    doc_type,
    branch_id,
    partner_id,
    doc_date,
        CASE
            WHEN (version = posted_version) THEN payload
            ELSE ( SELECT v.payload
               FROM public.accounting_event_versions v
              WHERE ((v.event_id = d.id) AND (v.version = d.posted_version)))
        END AS payload
   FROM public.accounting_events d
  WHERE ((posted_version IS NOT NULL) AND (status <> 'cancelled'::text));

--
-- Name: VIEW posted_event_payloads; Type: COMMENT; Schema: public; Owner: -
--

COMMENT ON VIEW public.posted_event_payloads IS 'Nội dung chứng từ theo phiên bản đang nằm trong sổ (đã định khoản, chưa huỷ).';

