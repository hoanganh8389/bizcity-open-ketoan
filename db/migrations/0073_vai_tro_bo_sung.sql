-- Một vai trò / người / phạm vi / mục đích chỉ một dòng đang mở (chưa thu hồi).
CREATE UNIQUE INDEX user_role_assignments_open_uq ON user_role_assignments (tenant_id, user_id, role, scope_type, coalesce(scope_id, 0), purpose) WHERE revoked_at IS NULL;
CREATE INDEX user_role_assignments_user_idx ON user_role_assignments (user_id) WHERE revoked_at IS NULL;

-- ── Chỉ thêm: không xoá, không TRUNCATE; UPDATE duy nhất là thu hồi một lần ────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION bizcity_user_role_assignments_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Lịch sử gán vai trò chỉ thêm (ADR-0027): không xoá, thu hồi bằng revoked_at.' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF OLD.revoked_at IS NOT NULL THEN
    RAISE EXCEPTION 'Dòng gán vai trò % đã thu hồi, không sửa lại (ADR-0027).', OLD.id USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF (NEW.tenant_id, NEW.user_id, NEW.role, NEW.scope_type, NEW.scope_id, NEW.purpose, NEW.valid_from, NEW.valid_to, NEW.reason, NEW.granted_by, NEW.granted_at)
     IS DISTINCT FROM (OLD.tenant_id, OLD.user_id, OLD.role, OLD.scope_type, OLD.scope_id, OLD.purpose, OLD.valid_from, OLD.valid_to, OLD.reason, OLD.granted_by, OLD.granted_at) THEN
    RAISE EXCEPTION 'Dòng gán vai trò chỉ thêm (ADR-0027): đổi vai trò / phạm vi / hiệu lực = thu hồi dòng cũ + gán dòng mới.' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;
COMMENT ON FUNCTION bizcity_user_role_assignments_guard() IS 'Bất biến user_role_assignments (ADR-0027): không xoá; UPDATE duy nhất là đặt revoked_* một lần.';
CREATE TRIGGER user_role_assignments_guard BEFORE UPDATE OR DELETE ON user_role_assignments FOR EACH ROW EXECUTE FUNCTION bizcity_user_role_assignments_guard();

CREATE OR REPLACE FUNCTION bizcity_user_role_assignments_truncate_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Không TRUNCATE lịch sử gán vai trò (ADR-0027).' USING ERRCODE = 'integrity_constraint_violation';
END $$;
COMMENT ON FUNCTION bizcity_user_role_assignments_truncate_guard() IS 'Chặn TRUNCATE user_role_assignments (ADR-0027).';
CREATE TRIGGER user_role_assignments_no_truncate BEFORE TRUNCATE ON user_role_assignments FOR EACH STATEMENT EXECUTE FUNCTION bizcity_user_role_assignments_truncate_guard();

