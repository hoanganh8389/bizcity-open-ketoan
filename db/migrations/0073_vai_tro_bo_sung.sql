CREATE TABLE user_role_assignments (
  id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint      NOT NULL REFERENCES tenants(id),
  user_id        bigint      NOT NULL REFERENCES users(id),
  role           text        NOT NULL CHECK (role IN ('owner', 'chief_accountant', 'accountant', 'viewer', 'developer', 'auditor')),
  scope_type     text        NOT NULL DEFAULT 'tenant' CHECK (scope_type IN ('tenant', 'branch', 'warehouse')),
  scope_id       bigint,
  purpose        text        NOT NULL DEFAULT 'operate' CHECK (purpose IN ('operate', 'approve', 'report', 'export')),
  valid_from     date        NOT NULL DEFAULT ((now() AT TIME ZONE 'Asia/Ho_Chi_Minh')::date),
  valid_to       date,
  reason         text        NOT NULL CHECK (length(btrim(reason)) >= 3),
  granted_by     text        NOT NULL,
  granted_at     timestamptz NOT NULL DEFAULT now(),
  revoked_by     text,
  revoked_at     timestamptz,
  revoke_reason  text,
  CONSTRAINT user_role_assignments_scope_chk CHECK ((scope_type = 'tenant') = (scope_id IS NULL)),
  CONSTRAINT user_role_assignments_valid_chk CHECK (valid_to IS NULL OR valid_to >= valid_from),
  CONSTRAINT user_role_assignments_revoke_chk CHECK ((revoked_at IS NULL) = (revoked_by IS NULL) AND (revoked_at IS NULL OR length(btrim(coalesce(revoke_reason, ''))) >= 3))
);

