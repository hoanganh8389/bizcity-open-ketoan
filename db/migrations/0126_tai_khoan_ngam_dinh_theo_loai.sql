-- [2026-11-13 Nguyễn Văn Thủy] Tài khoản ngầm định theo LOẠI chứng từ (đóng góp)
--
-- Mỗi loại (vd "Bán hàng trong nước chưa thanh toán") có các cột tài khoản (TK Nợ, TK Có, TK thuế GTGT, TK chiết khấu…).
-- Mỗi cột: danh sách tài khoản được chọn (lọc theo đầu số, vd 111;641) + tài khoản mặc định. Dòng chứng từ chọn loại thì
-- điền sẵn tài khoản mặc định và chỉ cho chọn trong danh sách — kế toán quyết luật ở đây.
-- Cột có `bind` là khoá hạch toán bộ định khoản đang dùng (posting_defaults): Ghi loại → đồng bộ khoá đó (một nơi khai).
-- Thay cho nhóm hạch toán (theo mặt hàng) và danh mục lý do ở giao diện. Dữ liệu gốc: db/seeds/tai-khoan-ngam-dinh-theo-loai.jsonl,
-- nạp khi đơn vị mở màn lần đầu.

CREATE TABLE account_default_types (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  code        text NOT NULL,
  grp         text NOT NULL DEFAULT '',
  name        text NOT NULL,
  columns     jsonb NOT NULL DEFAULT '[]'::jsonb,
  sort_order  integer NOT NULL DEFAULT 0,
  is_active   boolean NOT NULL DEFAULT true,
  created_by  text NOT NULL DEFAULT '',
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_by  text NOT NULL DEFAULT '',
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, code),
  CONSTRAINT account_default_types_columns_array CHECK (jsonb_typeof(columns) = 'array')
);
CREATE INDEX account_default_types_grp ON account_default_types (tenant_id, grp, sort_order);
COMMENT ON TABLE account_default_types IS 'Tài khoản ngầm định theo loại chứng từ (0126): cột tài khoản, danh sách được chọn, mặc định; cột bind đồng bộ posting_defaults.';

ALTER TABLE account_default_types ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_default_types FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON account_default_types USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ketoan_app') THEN
    GRANT SELECT, INSERT, UPDATE ON account_default_types TO ketoan_app;
    GRANT USAGE ON SEQUENCE account_default_types_id_seq TO ketoan_app;
  END IF;
END $$;
