ALTER TABLE purchase_policies ADD COLUMN version integer NOT NULL DEFAULT 1;
ALTER TABLE purchase_policies ADD COLUMN content_hash text;
COMMENT ON COLUMN purchase_policies.version IS 'Bản hiện hành (purchase_policy_versions / policy_registry cùng số).';
COMMENT ON COLUMN purchase_policies.content_hash IS 'Băm nội dung bản hiện hành; lưu lại mà băm không đổi thì không tạo bản mới.';

-- ── Nạp ngược: mỗi chính sách đang có = bản 1, hiệu lực từ đầu ─────────────────────────────────────────────────────────
-- Băm bản 1 = sha256 của jsonb::text (Postgres sắp khoá jsonb theo độ dài rồi chữ, nên khác contentHash của JS). Không sao:
-- băm là dấu của bản như sổ đăng ký đã ghi; còn "nội dung có đổi không" ứng dụng so bằng contentHash trên CẢ HAI ảnh chụp
-- (bản hiện hành và bản sắp lưu), không so với cột băm đã lưu.
WITH src AS (
  SELECT p.*, jsonb_build_object('code', p.code, 'kind', p.kind, 'name', p.name, 'scope', p.scope, 'rule', p.rule,
           'validFrom', p.valid_from, 'validTo', p.valid_to, 'priority', p.priority, 'isActive', p.is_active) AS snap
  FROM purchase_policies p
), v AS (
  INSERT INTO purchase_policy_versions (tenant_id, policy_id, version, effective_from, snapshot, content_hash, reason, created_by)
  SELECT tenant_id, id, 1, NULL, snap, encode(sha256(convert_to(snap::text, 'UTF8')), 'hex'), 'nạp ngược khi mở sổ đăng ký (0079)', 'system:migration-0079'
  FROM src
  RETURNING tenant_id, policy_id, content_hash, snapshot
)
INSERT INTO policy_registry (tenant_id, policy_key, policy_id, version, owner_module, rule_contract, scope, effective_from, status, store, store_ref, content_hash, published_by, reason)
SELECT v.tenant_id, v.snapshot->>'code', 'mua-hang:purchase_policies:' || v.policy_id, 1, 'mua-hang', 'purchase.' || (v.snapshot->>'kind') || '@1',
       v.snapshot->'scope', NULL, 'published', 'module', 'purchase_policy_versions:' || v.policy_id || '@1', v.content_hash, 'system:migration-0079', 'nạp ngược khi mở sổ đăng ký (0079)'
FROM v;

UPDATE purchase_policies p SET content_hash = v.content_hash
FROM purchase_policy_versions v WHERE v.tenant_id = p.tenant_id AND v.policy_id = p.id AND v.version = 1;

