CREATE TABLE policy_registry (
  id             bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint      NOT NULL REFERENCES tenants(id),
  policy_key     text        NOT NULL CHECK (length(btrim(policy_key)) BETWEEN 1 AND 128),
  policy_id      text        NOT NULL CHECK (policy_id ~ '^[a-z0-9-]+:[a-z0-9_.-]+:[A-Za-z0-9_.-]+$'),
  version        integer     NOT NULL CHECK (version >= 1),
  owner_module   text        NOT NULL CHECK (owner_module ~ '^[a-z0-9-]+$'),
  rule_contract  text        NOT NULL CHECK (rule_contract ~ '^[a-z0-9_]+(\.[a-z0-9_]+)+@[0-9]+$'),
  scope          jsonb       NOT NULL DEFAULT '{}',
  effective_from date,
  effective_to   date,
  status         text        NOT NULL DEFAULT 'published' CHECK (status IN ('published', 'retired')),
  store          text        NOT NULL CHECK (store IN ('module', 'settings', 'inline')),
  store_ref      text        NOT NULL DEFAULT '',
  content        jsonb,
  content_hash   text        NOT NULL CHECK (content_hash ~ '^[0-9a-f]{64}$'),
  legal_ref      text,
  published_by   text        NOT NULL,
  published_at   timestamptz NOT NULL DEFAULT now(),
  reason         text,
  findings       jsonb       NOT NULL DEFAULT '[]',
  CONSTRAINT policy_registry_range_chk CHECK (effective_to IS NULL OR effective_from IS NULL OR effective_to >= effective_from - 1),
  CONSTRAINT policy_registry_inline_chk CHECK ((store = 'inline') = (content IS NOT NULL))
);

COMMENT ON TABLE policy_registry IS 'Sổ đăng ký chính sách (ADR-0031): phong bì từng bản chính sách nghiệp vụ. Nội dung ở module chủ (store = module / settings) hoặc ngay dòng này (inline). Bản đã phát hành không sửa; chỉ được ngừng hoặc đóng hiệu lực khi có bản mới.';
