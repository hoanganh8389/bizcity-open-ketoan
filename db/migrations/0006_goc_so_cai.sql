-- Name: assert_entry_balanced(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.assert_entry_balanced() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
  v_debit  numeric;
  v_credit numeric;
BEGIN
  SELECT COALESCE(sum(debit), 0), COALESCE(sum(credit), 0)
    INTO v_debit, v_credit
    FROM ledger_lines WHERE entry_id = NEW.entry_id;
  IF v_debit <> v_credit THEN
    RAISE EXCEPTION 'Bút toán % không cân: Nợ % ≠ Có %', NEW.entry_id, v_debit, v_credit
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NULL;
END $$;

--
-- Name: assert_negative_only_on_reversal(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.assert_negative_only_on_reversal() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
  IF (NEW.debit < 0 OR NEW.credit < 0)
     AND NOT EXISTS (SELECT 1 FROM ledger_entries e WHERE e.id = NEW.entry_id AND e.is_reversal) THEN
    RAISE EXCEPTION 'Số tiền âm chỉ được dùng trong bút toán đảo (ghi số âm)'
      USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END $$;

