-- [2026-11-17 Nguyễn Văn Thủy] Thùng rác chung cho danh mục: Xoá → vào thùng rác (lưu nguyên dòng, kể cả item_id);
-- Khôi phục trả lại đúng dòng; Xoá vĩnh viễn gỡ hết (mặt hàng: cả item_id, mã, phân loại — nếu chưa có chứng từ dùng) (đóng góp)
--
-- catalog_trash   một dòng = một mục danh mục đã xoá. payload = { "<bảng>": [dòng to_jsonb …] } theo thứ tự chèn lại
--                 (bảng chính trước, bảng con sau). catalog = khoá danh mục phía máy chủ (vd tax-codes, dimensions.contract).
-- Cờ phiên bizcity.catalog_purge = 'on' (chỉ đặt trong giao dịch khôi phục / xoá vĩnh viễn của thùng rác) cho phép:
--   - mở lại mã hàng đã đóng khi khôi phục mặt hàng (giữ nguyên item_id);
--   - xoá items / item_codes / item_classification khi xoá vĩnh viễn mặt hàng chưa có chứng từ.

CREATE TABLE IF NOT EXISTS catalog_trash (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint NOT NULL,
  catalog     text NOT NULL,
  row_key     text NOT NULL,
  label       text NOT NULL DEFAULT '',
  payload     jsonb NOT NULL,
  deleted_by  text NOT NULL DEFAULT '',
  deleted_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS catalog_trash_tenant_catalog ON catalog_trash (tenant_id, catalog, deleted_at DESC);
COMMENT ON TABLE catalog_trash IS 'Thùng rác danh mục (0146): mục đã xoá, lưu nguyên dòng để khôi phục; xoá vĩnh viễn thì bỏ hẳn.';

ALTER TABLE catalog_trash ENABLE ROW LEVEL SECURITY;
ALTER TABLE catalog_trash FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON catalog_trash;
CREATE POLICY tenant_isolation ON catalog_trash USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ketoan_app') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE ON catalog_trash TO ketoan_app;
    GRANT USAGE ON SEQUENCE catalog_trash_id_seq TO ketoan_app;
    GRANT DELETE ON items, item_codes, item_classification TO ketoan_app;
  END IF;
END $$;

-- Cho phép bỏ qua chốt bất biến của mặt hàng khi (và chỉ khi) thùng rác đặt cờ phiên.
DO $$
DECLARE f text; d text;
BEGIN
  FOREACH f IN ARRAY ARRAY['bizcity_items_guard', 'bizcity_item_codes_guard', 'bizcity_item_classification_guard'] LOOP
    d := pg_get_functiondef(f::regproc);
    IF position('bizcity.catalog_purge' IN d) = 0 THEN
      d := regexp_replace(d, '\$function\$\s*BEGIN',
        E'$function$\nBEGIN\n  IF current_setting(''bizcity.catalog_purge'', true) = ''on'' THEN RETURN COALESCE(NEW, OLD); END IF;');
      EXECUTE d;
    END IF;
  END LOOP;
END $$;
