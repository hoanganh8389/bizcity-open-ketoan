-- 0076 Giá trị cấu hình có phiên bản (PHASE-029 E2, chữ chốt 30 §5, ADR-0028 D028-7 / D028-8, ECP-03).
--   Một kho khoá / giá trị cho mọi khoá registry có valueType (học cách tổ chức options của WordPress), nhưng KHÔNG ghi đè:
--   mỗi lần ghi là một dòng mới (phiên bản kế), có phạm vi, ngày hiệu lực, người ghi, lý do. Lịch sử chính là bảng này.
--   Đọc: user → branch → accounting_unit → tenant → mặc định registry; ở mỗi phạm vi lấy dòng valid_from ≤ ngày mới nhất
--   (packages/platform/src/core/settings.ts — getSetting). Khoá cũ ở tenants.settings.<đường> được ghi song song ở phạm vi
--   đơn vị để đường đọc cũ vẫn đúng (đợt 2 chuyển hết sang getSetting).
-- =============================================================================

CREATE TABLE setting_values (
  id          bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint      NOT NULL REFERENCES tenants(id),
  key         text        NOT NULL CHECK (key ~ '^bizcity\.[a-z0-9_]+(\.[a-z0-9_]+)+$'),
  scope_type  text        NOT NULL CHECK (scope_type IN ('tenant', 'accounting_unit', 'branch', 'user')),
  scope_id    text        NOT NULL DEFAULT '',
  value       jsonb       NOT NULL,
  valid_from  date        NOT NULL DEFAULT ((now() AT TIME ZONE 'Asia/Ho_Chi_Minh')::date),
  version     integer     NOT NULL CHECK (version >= 1),
  reason      text        CHECK (reason IS NULL OR length(btrim(reason)) >= 3),
  created_by  text        NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT setting_values_scope_chk CHECK ((scope_type = 'tenant') = (scope_id = ''))
);

COMMENT ON TABLE setting_values IS 'Giá trị cấu hình có phiên bản (bizcity_settings@1 §2, PHASE-029 E2). Chỉ thêm: mỗi lần ghi một dòng; giá trị hiệu lực = dòng valid_from ≤ ngày mới nhất ở phạm vi hẹp nhất có giá trị.';
COMMENT ON COLUMN setting_values.id IS 'Định danh dòng.';
COMMENT ON COLUMN setting_values.tenant_id IS 'Đơn vị.';
COMMENT ON COLUMN setting_values.key IS 'Khoá registry (docs/contracts/bizcity-settings.registry.json), dạng bizcity.<miền>.<khoá>.';
COMMENT ON COLUMN setting_values.scope_type IS 'Phạm vi: tenant | accounting_unit | branch | user (hẹp dần: user thắng trước).';
COMMENT ON COLUMN setting_values.scope_id IS 'Định danh phạm vi dạng chữ (accounting_units.id / branches.id / users.id); chuỗi rỗng khi tenant.';
COMMENT ON COLUMN setting_values.value IS 'Giá trị (jsonb) đã kiểm theo valueType của khoá.';
COMMENT ON COLUMN setting_values.valid_from IS 'Ngày bắt đầu hiệu lực (giờ Việt Nam).';
COMMENT ON COLUMN setting_values.version IS 'Phiên bản tăng dần theo (đơn vị, khoá, phạm vi).';
COMMENT ON COLUMN setting_values.reason IS 'Lý do đổi; bắt buộc với khoá loại A hoặc hiệu lực lùi về trước ngày ghi.';
COMMENT ON COLUMN setting_values.created_by IS 'Người ghi (user:<id> / apikey:<id>).';
COMMENT ON COLUMN setting_values.created_at IS 'Lúc ghi.';

CREATE UNIQUE INDEX setting_values_version_uq ON setting_values (tenant_id, key, scope_type, scope_id, version);
CREATE INDEX setting_values_lookup_idx ON setting_values (tenant_id, key, scope_type, scope_id, valid_from DESC, version DESC);

-- ── Chỉ thêm ─────────────────────────────────────────────────────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION bizcity_setting_values_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Giá trị cấu hình chỉ thêm (ECP-03): đổi = ghi phiên bản mới qua settings.set, không % dòng cũ.', lower(TG_OP) USING ERRCODE = 'integrity_constraint_violation';
END $$;
COMMENT ON FUNCTION bizcity_setting_values_guard() IS 'Bất biến setting_values: không UPDATE / DELETE / TRUNCATE — lịch sử cấu hình giữ nguyên (ECP-03, ECP-13).';
CREATE TRIGGER setting_values_guard BEFORE UPDATE OR DELETE ON setting_values FOR EACH ROW EXECUTE FUNCTION bizcity_setting_values_guard();
CREATE TRIGGER setting_values_no_truncate BEFORE TRUNCATE ON setting_values FOR EACH STATEMENT EXECUTE FUNCTION bizcity_setting_values_guard();

-- ── Cô lập đơn vị (như 0041) ─────────────────────────────────────────────────────────────────────────────────────────────
ALTER TABLE setting_values ENABLE ROW LEVEL SECURITY;
ALTER TABLE setting_values FORCE ROW LEVEL SECURITY;
CREATE POLICY tenant_isolation ON setting_values USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));

-- ── Khoá huỷ đệm cấu hình của đơn vị ────────────────────────────────────────────────────────────────────────────────────
ALTER TABLE tenants ADD COLUMN config_version bigint NOT NULL DEFAULT 0;
COMMENT ON COLUMN tenants.config_version IS 'Tăng 1 mỗi lần ghi cấu hình qua settings.set (bizcity_settings@1 §2.1) — khoá huỷ bộ nhớ đệm cấu hình của đơn vị (R-CACHE).';

