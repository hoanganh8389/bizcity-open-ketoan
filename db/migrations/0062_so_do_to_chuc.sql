-- [2026-11-03 10:39 AM Nguyễn Văn Thủy] SDTC — sơ đồ tổ chức làm gốc: cây Công ty → Miền → Chi nhánh → Tỉnh, chi nhánh / điểm kinh doanh gắn vào nút, nút đánh dấu đơn vị mua hàng chọn chi nhánh kho tổng (đóng góp)
-- =============================================================================
-- 0062 Sơ đồ tổ chức (SĐTC).
--      Cây quản lý của công ty: gốc "Công ty" (cấp 0) → cấp 1 Miền → cấp 2 Chi nhánh → cấp 3 Tỉnh (đi sâu hơn vẫn được).
--      Mỗi chi nhánh / điểm kinh doanh (branches) gắn đúng một nút (branches.org_unit_id) — báo cáo, bộ lọc cây, phân quyền
--      theo phạm vi đi theo cây này.
--      Nút đánh dấu "đơn vị mua hàng" chọn một chi nhánh kho tổng trong nhánh (purchase_branch_id): kho tổng đó là chi nhánh cha,
--      mọi chi nhánh khác trong nhánh là shop con. branches.level / parent_id (0020) từ nay là dữ liệu PHÁI SINH, tính lại từ
--      cây mỗi lần cây / gắn chi nhánh / đơn vị mua hàng thay đổi; công thức đặt hàng (order_formulas) vẫn khoá theo mã kho tổng.
--      Không xoá cứng nút: ngừng dùng (is_active = false).
-- =============================================================================

CREATE TABLE org_units (
  id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id          bigint      NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  code               text        NOT NULL,
  short_code         text        NOT NULL DEFAULT '',
  name               text        NOT NULL,
  alias              text        NOT NULL DEFAULT '',
  note               text        NOT NULL DEFAULT '',
  parent_id          bigint      REFERENCES org_units(id) ON DELETE RESTRICT,
  level              smallint    NOT NULL DEFAULT 0 CHECK (level BETWEEN 0 AND 9),
  path               text        NOT NULL DEFAULT '',
  sort_order         integer     NOT NULL DEFAULT 0,
  is_active          boolean     NOT NULL DEFAULT true,
  purchase_branch_id bigint      REFERENCES branches(id) ON DELETE SET NULL,
  created_by         text        NOT NULL DEFAULT '',
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_by         text        NOT NULL DEFAULT '',
  updated_at         timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, code),
  CHECK (parent_id IS NULL OR parent_id <> id)
);
CREATE INDEX org_units_parent_idx ON org_units (tenant_id, parent_id);
CREATE UNIQUE INDEX org_units_one_root ON org_units (tenant_id) WHERE parent_id IS NULL;

COMMENT ON TABLE org_units IS 'Sơ đồ tổ chức (0062): cây Công ty → Miền → Chi nhánh → Tỉnh; chi nhánh gắn nút qua branches.org_unit_id; nút có purchase_branch_id là đơn vị mua hàng.';
COMMENT ON COLUMN org_units.id IS 'Khoá nút.';
COMMENT ON COLUMN org_units.tenant_id IS 'Đơn vị.';
COMMENT ON COLUMN org_units.code IS 'Mã nút (BAC, PT, PTO…), duy nhất trong đơn vị.';
COMMENT ON COLUMN org_units.short_code IS 'Mã ngắn (mã ghép), vd 12, 21, 38.';
COMMENT ON COLUMN org_units.name IS 'Tên nút (Miền Bắc, Chi nhánh Phú Thọ…).';
COMMENT ON COLUMN org_units.alias IS 'Tên gọi khác để tìm kiếm.';
COMMENT ON COLUMN org_units.note IS 'Mô tả / ghi chú.';
COMMENT ON COLUMN org_units.parent_id IS 'Nút cha; NULL = gốc Công ty (mỗi đơn vị một gốc).';
COMMENT ON COLUMN org_units.level IS 'Cấp: 0 = gốc Công ty, 1 = Miền, 2 = Chi nhánh, 3 = Tỉnh… (tính từ cây).';
COMMENT ON COLUMN org_units.path IS 'Đường dẫn mã từ gốc, nối bằng \\ (Công ty\\BAC\\PT\\PTO) — tính từ cây, để hiển thị / tìm.';
COMMENT ON COLUMN org_units.sort_order IS 'Thứ tự hiển thị trong cùng nút cha.';
COMMENT ON COLUMN org_units.is_active IS 'Đang dùng; false = ngừng dùng (không xoá cứng).';
COMMENT ON COLUMN org_units.purchase_branch_id IS 'Đơn vị mua hàng: chi nhánh kho tổng trong nhánh (vd PT → 08000). NULL = nút không phải đơn vị mua hàng. Chi nhánh trong nhánh thuộc đơn vị mua hàng gần nhất phía trên.';
COMMENT ON COLUMN org_units.created_by IS 'Người tạo.';
COMMENT ON COLUMN org_units.created_at IS 'Lúc tạo.';
COMMENT ON COLUMN org_units.updated_by IS 'Người sửa gần nhất.';
COMMENT ON COLUMN org_units.updated_at IS 'Lúc sửa gần nhất.';

ALTER TABLE branches ADD COLUMN org_unit_id bigint REFERENCES org_units(id) ON DELETE SET NULL;
CREATE INDEX branches_org_unit_idx ON branches (tenant_id, org_unit_id);
COMMENT ON COLUMN branches.org_unit_id IS 'Nút sơ đồ tổ chức chi nhánh / điểm kinh doanh thuộc về (0062). NULL = chưa gắn.';

