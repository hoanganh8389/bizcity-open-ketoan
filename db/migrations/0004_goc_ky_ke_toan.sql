CREATE TABLE public.fiscal_periods (
    id bigint NOT NULL,
    tenant_id bigint NOT NULL,
    year smallint NOT NULL,
    month smallint NOT NULL,
    start_date date NOT NULL,
    end_date date NOT NULL,
    CONSTRAINT fiscal_periods_check CHECK ((end_date >= start_date)),
    CONSTRAINT fiscal_periods_check1 CHECK ((EXTRACT(year FROM start_date) = EXTRACT(year FROM end_date))),
    CONSTRAINT fiscal_periods_month_check CHECK (((month >= 1) AND (month <= 12)))
);

--
-- Name: TABLE fiscal_periods; Type: COMMENT; Schema: public; Owner: -
--

COMMENT ON TABLE public.fiscal_periods IS 'Kỳ kế toán theo tháng. Tự tạo khi có chứng từ rơi vào tháng chưa có kỳ.';

