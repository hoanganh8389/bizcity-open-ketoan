-- [2026-11-13 Nguyễn Văn Thủy] Loại kho + nghiệp vụ dùng loại kho nào (theo thứ tự ưu tiên) (đóng góp)
--
-- warehouse_types: danh mục loại kho (12 loại gốc theo mô tả nghiệp vụ, thêm được loại mới). Công tắc:
--   can_sell      hàng trong kho được bán (tính vào tồn khả dụng)
--   owned         hàng thuộc sở hữu đơn vị (tính giá vốn, ghi sổ kho); tắt = chỉ theo dõi số lượng (nhận giữ hộ)
--   track_expiry  theo dõi hạn dùng, cảnh báo cận / hết hạn
--   account_prefix đầu số TK kho của loại (156, 157…) — trống = theo Tài khoản ngầm định
-- Luật: mã viết hoa; không sở hữu thì không được bán (CHECK); loại gốc không đổi mã.
-- warehouse_type_ops: mỗi nghiệp vụ (nhập mua, bán, khách trả, chuyển kho…) dùng được những loại nào, theo thứ tự ưu tiên —
--   màn hình tự chọn kho thuộc loại đứng đầu; chọn kho loại không có trong danh sách thì chặn. Thêm loại mới chỉ cần đưa vào danh sách.
-- warehouses.type_code: loại của kho. Kho khuyến mại cũ (is_promo) → KKM, còn lại → KHH; is_promo tự theo loại (KKM).

CREATE TABLE warehouse_types (
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id      bigint NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  code           text NOT NULL CHECK (code ~ '^[A-Z][A-Z0-9_]{1,11}$'),
  name           text NOT NULL,
  purpose        text NOT NULL DEFAULT '',
  can_sell       boolean NOT NULL DEFAULT false,
  owned          boolean NOT NULL DEFAULT true,
  track_expiry   boolean NOT NULL DEFAULT false,
  account_prefix text NOT NULL DEFAULT '' CHECK (account_prefix ~ '^[0-9]{0,12}$'),
  is_system      boolean NOT NULL DEFAULT false,
  is_active      boolean NOT NULL DEFAULT true,
  sort_order     integer NOT NULL DEFAULT 0,
  updated_by     text NOT NULL DEFAULT '',
  updated_at     timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, code),
  CONSTRAINT warehouse_types_sell_needs_owned CHECK (owned OR NOT can_sell)
);
COMMENT ON TABLE warehouse_types IS 'Loại kho (0128): được bán, thuộc sở hữu, theo dõi hạn dùng, đầu số TK kho.';

CREATE TABLE warehouse_type_ops (
  tenant_id  bigint NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  op         text NOT NULL CHECK (op ~ '^[a-z_]{2,40}$'),
  type_codes text[] NOT NULL DEFAULT '{}',
  updated_by text NOT NULL DEFAULT '',
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, op)
);
COMMENT ON TABLE warehouse_type_ops IS 'Nghiệp vụ → loại kho được dùng theo thứ tự ưu tiên (0128).';

ALTER TABLE warehouses ADD COLUMN type_code text NOT NULL DEFAULT 'KHH';
COMMENT ON COLUMN warehouses.type_code IS 'Loại kho (warehouse_types.code), 0128.';

