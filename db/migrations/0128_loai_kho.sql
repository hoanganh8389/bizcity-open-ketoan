UPDATE warehouses SET type_code = CASE WHEN is_promo THEN 'KKM' ELSE 'KHH' END;

-- is_promo (cũ, tồn max… còn đọc) đi theo loại kho: một nơi khai
CREATE OR REPLACE FUNCTION bizcity_warehouse_type_sync() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  -- nơi gửi cũ chỉ đặt is_promo (không gửi loại): suy ra loại
  IF TG_OP = 'INSERT' THEN
    IF NEW.is_promo AND NEW.type_code = 'KHH' THEN NEW.type_code := 'KKM'; END IF;
  ELSIF NEW.is_promo IS DISTINCT FROM OLD.is_promo AND NEW.type_code = OLD.type_code THEN
    NEW.type_code := CASE WHEN NEW.is_promo THEN 'KKM' WHEN OLD.type_code = 'KKM' THEN 'KHH' ELSE OLD.type_code END;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM warehouse_types t WHERE t.tenant_id = NEW.tenant_id AND t.code = NEW.type_code) THEN
    RAISE EXCEPTION 'Loại kho % chưa có trong danh mục Loại kho', NEW.type_code USING ERRCODE = 'foreign_key_violation';
  END IF;
  NEW.is_promo := NEW.type_code = 'KKM';
  RETURN NEW;
END $$;
CREATE TRIGGER warehouses_type_sync BEFORE INSERT OR UPDATE OF type_code, is_promo ON warehouses
  FOR EACH ROW EXECUTE FUNCTION bizcity_warehouse_type_sync();
COMMENT ON FUNCTION bizcity_warehouse_type_sync() IS 'Kho phải thuộc một loại có trong danh mục; is_promo = (loại KKM) (0128).';

-- đơn vị mới: nạp loại kho khi tạo đơn vị
CREATE OR REPLACE FUNCTION bizcity_tenant_seed_warehouse_types() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  PERFORM bizcity_seed_warehouse_types(NEW.id);
  RETURN NEW;
END $$;
CREATE TRIGGER tenants_seed_warehouse_types AFTER INSERT ON tenants FOR EACH ROW EXECUTE FUNCTION bizcity_tenant_seed_warehouse_types();
COMMENT ON FUNCTION bizcity_tenant_seed_warehouse_types() IS 'Đơn vị mới có sẵn 12 loại kho gốc (0128).';
