-- Mỗi lần bấm Tính giá vốn cho một chi nhánh (điểm tính giá vốn, 0149) lưu một dòng costing_runs, gắn MỐC CƠ CẤU: id + uid
-- (định danh bất biến) của nút cơ cấu, mã / tên lúc tính. costing_run_lines chụp bảng đơn giá các mã hàng của chi nhánh tại lần
-- tính đó (tồn đầu, nhập tính giá, đơn giá, xuất, tồn cuối, nguồn giá) — tính lại thì thêm lần mới, lần cũ giữ để xem lại.
-- Phiếu giá vốn hàng xuất (một phiếu / shop / tháng, đảo và ghi lại mỗi lần tính) liệt kê ở vouchers.

CREATE TABLE IF NOT EXISTS costing_runs (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint NOT NULL,
  org_unit_id   bigint,
  org_uid       text NOT NULL DEFAULT '',
  center_code   text NOT NULL,
  center_name   text NOT NULL DEFAULT '',
  year          int NOT NULL,
  month         int NOT NULL CHECK (month BETWEEN 1 AND 12),
  date_from     date NOT NULL,
  date_to       date NOT NULL,
  items         int NOT NULL DEFAULT 0,
  total         numeric(20, 2) NOT NULL DEFAULT 0,
  imported      int NOT NULL DEFAULT 0,
  vouchers      jsonb NOT NULL DEFAULT '[]'::jsonb,
  run_by        text NOT NULL DEFAULT '',
  run_at        timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS costing_runs_center ON costing_runs (tenant_id, center_code, run_at DESC);
COMMENT ON TABLE costing_runs IS 'Lần tính giá vốn theo chi nhánh (0150): mốc cơ cấu (org_unit_id, org_uid), kỳ, khoảng ngày, tổng, phiếu giá vốn.';

CREATE TABLE IF NOT EXISTS costing_run_lines (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id     bigint NOT NULL,
  run_id        bigint NOT NULL REFERENCES costing_runs(id) ON DELETE CASCADE,
  sku           text NOT NULL,
  item_id       text,
  opening_qty   numeric NOT NULL DEFAULT 0,
  opening_value numeric NOT NULL DEFAULT 0,
  in_qty        numeric NOT NULL DEFAULT 0,
  in_value      numeric NOT NULL DEFAULT 0,
  unit_cost     numeric NOT NULL DEFAULT 0,
  out_qty       numeric NOT NULL DEFAULT 0,
  closing_qty   numeric NOT NULL DEFAULT 0,
  closing_value numeric NOT NULL DEFAULT 0,
  gift_qty      numeric NOT NULL DEFAULT 0,
  cost_source   text NOT NULL DEFAULT 'computed'
);
CREATE INDEX IF NOT EXISTS costing_run_lines_run ON costing_run_lines (run_id);
COMMENT ON TABLE costing_run_lines IS 'Bảng đơn giá các mã hàng của chi nhánh tại một lần tính giá vốn (0150).';

