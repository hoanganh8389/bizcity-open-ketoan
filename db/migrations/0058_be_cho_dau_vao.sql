CREATE TABLE intake_inbox (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id       bigint      NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  received_at     timestamptz NOT NULL DEFAULT now(),
  last_seen_at    timestamptz NOT NULL DEFAULT now(),
  channel         text        NOT NULL CHECK (channel IN ('api', 'batch', 'submit', 'app', 'connector', 'mcp', 'trial')),
  source_system   text,
  actor           text        NOT NULL,
  app_key         text,
  doc_key         text,
  doc_type        text,
  version         integer,
  payload_raw     jsonb       NOT NULL,
  payload_hash    text        NOT NULL,
  payload_bytes   integer     NOT NULL,
  patches         jsonb       NOT NULL DEFAULT '[]',
  findings        jsonb       NOT NULL DEFAULT '[]',
  score           smallint    NOT NULL CHECK (score BETWEEN 0 AND 100),
  door_error      jsonb,
  attempt_no      integer     NOT NULL DEFAULT 1,
  status          text        NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'trial', 'resubmitted', 'fixed_at_source', 'accepted', 'dismissed')),
  event_id        bigint      REFERENCES accounting_events(id),
  accepted_codes  text[]      NOT NULL DEFAULT '{}',
  resolved_by     text,
  resolved_at     timestamptz,
  resolution_note text
);

CREATE UNIQUE INDEX intake_inbox_open_dedupe ON intake_inbox (tenant_id, payload_hash) WHERE status IN ('open', 'trial');
CREATE INDEX intake_inbox_doc_idx ON intake_inbox (tenant_id, doc_key) WHERE status = 'open';
CREATE INDEX intake_inbox_status_idx ON intake_inbox (tenant_id, status, received_at DESC);

