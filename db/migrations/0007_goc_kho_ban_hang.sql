-- Name: sales_payments; Type: VIEW; Schema: public; Owner: -
--

CREATE VIEW public.sales_payments AS
 SELECT ((d.id * 1000) + p.ord) AS id,
    d.tenant_id,
    d.id AS event_id,
    d.branch_id,
    d.doc_date,
    (
        CASE
            WHEN (d.doc_type = 'sale_return'::text) THEN '-1'::integer
            ELSE 1
        END)::smallint AS sign,
    COALESCE((p.j ->> 'methodCode'::text), ''::text) AS method_code,
    COALESCE(((p.j ->> 'amount'::text))::numeric, (0)::numeric) AS amount
   FROM (public.posted_event_payloads d
     CROSS JOIN LATERAL jsonb_array_elements(COALESCE((d.payload -> 'payments'::text), '[]'::jsonb)) WITH ORDINALITY p(j, ord))
  WHERE (d.doc_type = ANY (ARRAY['sale'::text, 'sale_return'::text]))
UNION ALL
 SELECT (- ((pay.id * 1000) + l.ord)) AS id,
    pay.tenant_id,
    inv.id AS event_id,
    pay.branch_id,
    pay.doc_date,
    (
        CASE
            WHEN ((pay.payload ->> 'direction'::text) = 'out'::text) THEN '-1'::integer
            ELSE 1
        END)::smallint AS sign,
    COALESCE((pay.payload ->> 'methodCode'::text), ''::text) AS method_code,
    COALESCE(((l.j ->> 'amount'::text))::numeric, (0)::numeric) AS amount
   FROM ((public.posted_event_payloads pay
     CROSS JOIN LATERAL jsonb_array_elements(COALESCE((pay.payload -> 'lines'::text), '[]'::jsonb)) WITH ORDINALITY l(j, ord))
     JOIN public.accounting_events inv ON (((inv.tenant_id = pay.tenant_id) AND (inv.doc_key = (l.j ->> 'invoiceDocKey'::text)) AND (inv.doc_type = ANY (ARRAY['sale'::text, 'sale_return'::text])))))
  WHERE (pay.doc_type = 'customer_payment'::text)
UNION ALL
 SELECT (((d.id * 1000) + 500) + o.ord) AS id,
    d.tenant_id,
    d.id AS event_id,
    d.branch_id,
    d.doc_date,
    (1)::smallint AS sign,
    'DOITRU'::text AS method_code,
    COALESCE(((o.j ->> 'amount'::text))::numeric, (0)::numeric) AS amount
   FROM (public.posted_event_payloads d
     CROSS JOIN LATERAL jsonb_array_elements(COALESCE((d.payload -> 'offsets'::text), '[]'::jsonb)) WITH ORDINALITY o(j, ord))
  WHERE (d.doc_type = 'sale'::text);

--
-- Name: VIEW sales_payments; Type: COMMENT; Schema: public; Owner: -
--

COMMENT ON VIEW public.sales_payments IS 'Tiền thu / trả khách của chứng từ bán hàng: kèm phiếu, phiếu thanh toán khách hàng (gắn về phiếu bán / hoàn), đối trừ đổi trả (DOITRU).';

