CREATE TABLE library_settings (
  tenant_id   bigint      NOT NULL REFERENCES tenants(id),
  library_id  text        NOT NULL CHECK (library_id ~ '^[a-z0-9-]+\.[a-z0-9][a-z0-9-]{1,48}$'),
  version     integer     NOT NULL CHECK (version >= 1),
  config      jsonb       NOT NULL CHECK (jsonb_typeof(config) = 'object'),
  reason      text        NOT NULL CHECK (length(btrim(reason)) BETWEEN 5 AND 500),
  created_by  text        NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (tenant_id, library_id, version)
);

COMMENT ON TABLE  library_settings IS 'Cấu hình thư viện theo đơn vị (S030-49b, PHASE-030 · 26 §7.1): mỗi lần đổi một phiên bản mới, chỉ thêm; bản hiện hành = phiên bản lớn nhất.';
COMMENT ON COLUMN library_settings.tenant_id  IS 'Đơn vị.';
COMMENT ON COLUMN library_settings.library_id IS 'id thư viện <miền>.<tên>.';
COMMENT ON COLUMN library_settings.version    IS 'Phiên bản cấu hình của đơn vị cho thư viện này (1, 2, …).';
COMMENT ON COLUMN library_settings.config     IS '{ enabled?, atPolicy?: docDate|today, ruleLevels?: { mã luật: warn|info }, overrides?: { mã mục: [{ from, value, reason, basisKey? }] } }.';
COMMENT ON COLUMN library_settings.reason     IS 'Lý do đổi (bắt buộc).';
COMMENT ON COLUMN library_settings.created_by IS 'Người đổi (id người dùng / khoá).';
COMMENT ON COLUMN library_settings.created_at IS 'Lúc đổi.';

CREATE OR REPLACE FUNCTION bizcity_library_settings_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'Cấu hình thư viện chỉ thêm (ECP-03): đổi = ghi phiên bản mới qua core.library.configure, không % dòng cũ.', lower(TG_OP) USING ERRCODE = 'integrity_constraint_violation';
END $$;
COMMENT ON FUNCTION bizcity_library_settings_guard() IS 'Bất biến library_settings: không UPDATE / DELETE / TRUNCATE — lịch sử cấu hình thư viện giữ nguyên (ECP-03, ECP-13).';
CREATE TRIGGER library_settings_guard BEFORE UPDATE OR DELETE ON library_settings FOR EACH ROW EXECUTE FUNCTION bizcity_library_settings_guard();
CREATE TRIGGER library_settings_no_truncate BEFORE TRUNCATE ON library_settings FOR EACH STATEMENT EXECUTE FUNCTION bizcity_library_settings_guard();

CREATE TABLE library_change_requests (
  id               bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id        bigint      NOT NULL REFERENCES tenants(id),
  library_id       text        NOT NULL CHECK (library_id ~ '^[a-z0-9-]+\.[a-z0-9][a-z0-9-]{1,48}$'),
  item_code        text        CHECK (item_code IS NULL OR length(item_code) BETWEEN 1 AND 80),
  kind             text        NOT NULL CHECK (kind IN ('them-muc', 'sua-gia-tri', 'can-cu', 'bao-sai', 'ngung-dung')),
  content          text        NOT NULL CHECK (length(btrim(content)) BETWEEN 5 AND 2000),
  basis_key        text        CHECK (basis_key IS NULL OR length(basis_key) BETWEEN 1 AND 80),
  status           text        NOT NULL DEFAULT 'gui' CHECK (status IN ('gui', 'nhan', 'da-vao', 'tu-choi', 'rut')),
  resolved_version text        CHECK (resolved_version IS NULL OR resolved_version ~ '^\d+\.\d+\.\d+$'),
  status_note      text        CHECK (status_note IS NULL OR length(status_note) <= 500),
  created_by       text        NOT NULL,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_by       text,
  updated_at       timestamptz
);

COMMENT ON TABLE  library_change_requests IS 'Phiếu đề xuất cập nhật thư viện của đơn vị gửi Nhóm Lõi (S030-49b, PHASE-030 · 26 §5): không đổi thư viện gốc; vào bản mới qua PR. Không lưu dữ liệu khách / số tiền chứng từ (R-SEC-10).';
COMMENT ON COLUMN library_change_requests.id               IS 'Số phiếu.';
COMMENT ON COLUMN library_change_requests.tenant_id        IS 'Đơn vị gửi.';
COMMENT ON COLUMN library_change_requests.library_id       IS 'Thư viện được đề xuất.';
COMMENT ON COLUMN library_change_requests.item_code        IS 'Mã mục liên quan (trống khi đề xuất thêm mục mới).';
COMMENT ON COLUMN library_change_requests.kind             IS 'them-muc · sua-gia-tri · can-cu · bao-sai · ngung-dung.';
COMMENT ON COLUMN library_change_requests.content          IS 'Nội dung đề xuất (giá trị mới, khoảng hiệu lực, lý do).';
COMMENT ON COLUMN library_change_requests.basis_key        IS 'Mã / bí danh văn bản căn cứ trong vn.can-cu-phap-ly (tuỳ chọn).';
COMMENT ON COLUMN library_change_requests.status           IS 'gui (đã gửi) → nhan (Nhóm Lõi nhận) → da-vao (đã vào bản) | tu-choi; rut = người gửi rút.';
COMMENT ON COLUMN library_change_requests.resolved_version IS 'Bản thư viện đã đưa đề xuất vào (khi da-vao).';
COMMENT ON COLUMN library_change_requests.status_note      IS 'Ghi chú lần đổi trạng thái gần nhất.';
COMMENT ON COLUMN library_change_requests.created_by       IS 'Người gửi.';
COMMENT ON COLUMN library_change_requests.created_at       IS 'Lúc gửi.';
COMMENT ON COLUMN library_change_requests.updated_by       IS 'Người đổi trạng thái gần nhất.';
COMMENT ON COLUMN library_change_requests.updated_at       IS 'Lúc đổi trạng thái gần nhất.';

CREATE INDEX library_change_requests_lib ON library_change_requests (tenant_id, library_id, status);
COMMENT ON INDEX library_change_requests_lib IS 'Danh sách phiếu theo thư viện, trạng thái.';

CREATE OR REPLACE FUNCTION bizcity_library_change_requests_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION 'Phiếu đề xuất thư viện không xoá (ECP-13): rút = đổi trạng thái rut.' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  IF NEW.tenant_id <> OLD.tenant_id OR NEW.library_id <> OLD.library_id OR NEW.kind <> OLD.kind OR NEW.content <> OLD.content
     OR NEW.item_code IS DISTINCT FROM OLD.item_code OR NEW.basis_key IS DISTINCT FROM OLD.basis_key OR NEW.created_by <> OLD.created_by OR NEW.created_at <> OLD.created_at THEN
    RAISE EXCEPTION 'Nội dung phiếu đề xuất không sửa — chỉ đổi trạng thái; nội dung khác thì gửi phiếu mới.' USING ERRCODE = 'integrity_constraint_violation';
  END IF;
  RETURN NEW;
END $$;
COMMENT ON FUNCTION bizcity_library_change_requests_guard() IS 'Phiếu đề xuất: không xoá; chỉ đổi trạng thái / bản đã vào / ghi chú — nội dung giữ nguyên.';
CREATE TRIGGER library_change_requests_guard BEFORE UPDATE OR DELETE ON library_change_requests FOR EACH ROW EXECUTE FUNCTION bizcity_library_change_requests_guard();

