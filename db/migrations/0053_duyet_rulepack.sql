-- 0053 Duyệt rulepack tại bản cài — rulepack_approvals (ADR-0015; PHASE-020).
--      Bản cài tự chủ (self-host): chủ đơn vị / kế toán trưởng duyệt một rulepack cho đơn vị mình, ghi tên người duyệt kế toán
--      (và người duyệt thuế với miền thuế / hoá đơn / quản lý thuế / lương). Lượt duyệt gắn ĐÚNG phiên bản + băm nội dung
--      rulepack: cập nhật gói rulepack làm đổi băm ⇒ lượt duyệt cũ hết hiệu lực, phải duyệt lại.
--      Chỉ thêm: thu hồi là một dòng action = 'revoke'. Lượt duyệt mới nhất (theo id) của (đơn vị, rulepack) quyết định.
--      Kết quả dựa trên duyệt tại đơn vị mang nhãn "Đạt theo duyệt của đơn vị", không mang nhãn Bizcity (ADR-0015 §3).
-- =============================================================================

CREATE TABLE IF NOT EXISTS rulepack_approvals (
  id                   bigint      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id            bigint      NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  rulepack_id          text        NOT NULL,
  rulepack_version     text        NOT NULL,
  rulepack_hash        text        NOT NULL CHECK (rulepack_hash ~ '^sha256:[0-9a-f]{64}$'),
  action               text        NOT NULL CHECK (action IN ('approve', 'revoke')),
  accounting_reviewer  text,
  tax_reviewer         text,
  note                 text        NOT NULL,
  actor                text        NOT NULL,
  created_at           timestamptz NOT NULL DEFAULT now(),
  CHECK (action = 'revoke' OR (accounting_reviewer IS NOT NULL AND length(btrim(accounting_reviewer)) >= 3))
);
CREATE INDEX IF NOT EXISTS rulepack_approvals_tenant_idx ON rulepack_approvals (tenant_id, rulepack_id, id DESC);

CREATE OR REPLACE FUNCTION rulepack_approvals_guard() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF TG_OP = 'DELETE' AND pg_trigger_depth() > 1 THEN RETURN OLD; END IF;
  RAISE EXCEPTION 'Lượt duyệt rulepack đã lưu không sửa / xoá được (chỉ thêm; thu hồi bằng dòng mới)' USING ERRCODE = 'P0001';
END $$;
DROP TRIGGER IF EXISTS rulepack_approvals_guard ON rulepack_approvals;
CREATE TRIGGER rulepack_approvals_guard BEFORE UPDATE OR DELETE ON rulepack_approvals FOR EACH ROW EXECUTE FUNCTION rulepack_approvals_guard();

ALTER TABLE rulepack_approvals ENABLE ROW LEVEL SECURITY;
ALTER TABLE rulepack_approvals FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON rulepack_approvals;
CREATE POLICY tenant_isolation ON rulepack_approvals USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));

COMMENT ON TABLE rulepack_approvals IS 'Lượt duyệt / thu hồi rulepack tại bản cài (ADR-0015): đơn vị tự duyệt, chỉ thêm; dòng mới nhất của (đơn vị, rulepack) quyết định.';
COMMENT ON COLUMN rulepack_approvals.id IS 'Số lượt.';
COMMENT ON COLUMN rulepack_approvals.tenant_id IS 'Đơn vị.';
COMMENT ON COLUMN rulepack_approvals.rulepack_id IS 'Mã rulepack trong @bizcity/vn-rulepacks.';
COMMENT ON COLUMN rulepack_approvals.rulepack_version IS 'Phiên bản rulepack lúc duyệt; khác phiên bản đang nạp ⇒ lượt duyệt không còn hiệu lực.';
COMMENT ON COLUMN rulepack_approvals.rulepack_hash IS 'SHA-256 nội dung rulepack + các ca lúc duyệt; đổi một chữ ⇒ lượt duyệt không còn hiệu lực.';
COMMENT ON COLUMN rulepack_approvals.action IS 'approve = duyệt; revoke = thu hồi lượt duyệt trước.';
COMMENT ON COLUMN rulepack_approvals.accounting_reviewer IS 'Họ tên (và chứng chỉ nếu có) người duyệt kế toán — bắt buộc khi duyệt.';
COMMENT ON COLUMN rulepack_approvals.tax_reviewer IS 'Họ tên người duyệt thuế — bắt buộc với miền thuế / hoá đơn / quản lý thuế / lương (kiểm ở Kernel).';
COMMENT ON COLUMN rulepack_approvals.note IS 'Phạm vi đã rà, căn cứ, lý do duyệt / thu hồi.';
COMMENT ON COLUMN rulepack_approvals.actor IS 'Tài khoản thực hiện (người đăng nhập; khoá API / AI không duyệt được).';
COMMENT ON COLUMN rulepack_approvals.created_at IS 'Lúc duyệt / thu hồi.';
