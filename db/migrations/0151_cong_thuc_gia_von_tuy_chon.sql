-- [2026-11-17 Nguyễn Văn Thủy] Công thức giá vốn tuỳ chọn: mỗi lần tính chọn một công thức (bộ lựa chọn) do người dùng đặt (đóng góp)
--
-- inventory_movements.tax_amount / discount_amount  thuế GTGT và chiết khấu của dòng (cùng dấu với amount) — để công thức lấy giá
--                                                  nhập "trước chiết khấu" hoặc "gồm VAT". Điền ngược từ payload chứng từ đã ghi.
-- costing_formulas   danh mục công thức: mã, tên, options:
--   price          'net' (chưa VAT, đã trừ CK — mặc định) | 'before_discount' (chưa VAT, chưa trừ CK) | 'with_vat' (gồm VAT, đã trừ CK)
--   costAlloc      true: cộng chi phí mua hàng phân bổ (vận chuyển…)
--   rebateAlloc    true: trừ thưởng / chiết khấu nhãn hàng phân bổ
--   purchaseReturn 'reason' (theo lý do — mặc định) | 'doc' (theo giá trị phiếu trả) | 'opening' (định giá theo tồn đầu)
--   transferIn     'doc' (theo giá trên phiếu, phiếu không có giá thì giá vốn bên gửi — mặc định) | 'sender' (luôn giá vốn bên gửi)
--   adjustIn       true: nhập điều chỉnh tính vào giá (theo cờ lý do)
-- costing_runs.formula_code / formula_name / formula  công thức đã dùng ở lần tính (chụp lại options lúc tính).

ALTER TABLE inventory_movements ADD COLUMN IF NOT EXISTS tax_amount numeric NOT NULL DEFAULT 0;
ALTER TABLE inventory_movements ADD COLUMN IF NOT EXISTS discount_amount numeric NOT NULL DEFAULT 0;
COMMENT ON COLUMN inventory_movements.tax_amount IS 'Thuế GTGT của dòng, cùng dấu amount (0151).';
COMMENT ON COLUMN inventory_movements.discount_amount IS 'Chiết khấu của dòng (đã trừ trong amount), cùng dấu amount (0151).';

UPDATE inventory_movements m
   SET tax_amount = sign(m.amount) * abs(COALESCE((e.payload->'lines'->(m.line_no - 1)->>'taxAmount')::numeric, 0)),
       discount_amount = sign(m.amount) * abs(COALESCE((e.payload->'lines'->(m.line_no - 1)->>'discount')::numeric, 0))
  FROM accounting_events e
 WHERE e.id = m.event_id AND m.kind IN ('purchase', 'purchase_return') AND m.amount IS NOT NULL AND m.amount <> 0
   AND jsonb_typeof(e.payload->'lines') = 'array';

CREATE TABLE IF NOT EXISTS costing_formulas (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id   bigint NOT NULL,
  code        text NOT NULL,
  name        text NOT NULL,
  options     jsonb NOT NULL DEFAULT '{}'::jsonb,
  is_default  boolean NOT NULL DEFAULT false,
  note        text NOT NULL DEFAULT '',
  updated_by  text NOT NULL DEFAULT '',
  updated_at  timestamptz NOT NULL DEFAULT now(),
  UNIQUE (tenant_id, code)
);
COMMENT ON TABLE costing_formulas IS 'Công thức giá vốn người dùng đặt (0151): giá nhập, chi phí / thưởng phân bổ, hàng trả NCC, nhận chi nhánh khác, nhập điều chỉnh.';
ALTER TABLE costing_formulas ENABLE ROW LEVEL SECURITY;
ALTER TABLE costing_formulas FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS tenant_isolation ON costing_formulas;
CREATE POLICY tenant_isolation ON costing_formulas USING (bizcity_tenant_visible(tenant_id)) WITH CHECK (bizcity_tenant_visible(tenant_id));

ALTER TABLE costing_runs ADD COLUMN IF NOT EXISTS formula_code text NOT NULL DEFAULT '';
ALTER TABLE costing_runs ADD COLUMN IF NOT EXISTS formula_name text NOT NULL DEFAULT '';
ALTER TABLE costing_runs ADD COLUMN IF NOT EXISTS formula jsonb NOT NULL DEFAULT '{}'::jsonb;

